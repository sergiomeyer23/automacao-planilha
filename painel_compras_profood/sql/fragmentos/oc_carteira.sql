-- Itens de OC do escopo da carteira: negociados no período (qualquer status) OU com saldo aberto (qualquer data).
occ_it AS (
    SELECT C.NUNOTA, I.SEQUENCIA, C.CODEMP, C.CODTIPOPER, C.DHTIPOPER, C.CODPARC, TP.GRUPO_PRECO, I.CODPROD,
           C.STATUSNOTA,
           TRUNC(C.DTNEG) AS DT_NEG,
           TRUNC(C.DTPREVENT) AS DT_PREV,
           NVL(I.PENDENTE, 'S') AS PENDENTE,
           NVL(I.CANCELADO, 'N') AS CANCELADO,
           NVL(I.QTDNEG, 0) AS QTDNEG,
           NVL(I.QTDENTREGUE, 0) AS QTDENT,
           NVL(I.VLRTOT, 0) AS VLRTOT,
           I.CODVOL AS UNID_ITEM,
           P.CODVOL AS UNID_PADRAO,
           CASE WHEN P.LEADTIME > 0 THEN P.LEADTIME END AS LT_CAD,
           NULLIF(TRIM(C.AD_OSTUICIAL), '') AS OS,
           {{FATOR I, P, VO}} AS FATOR,
           {{STATUS_CONV I, P, VO}} AS STATUS_CONV,
           CASE WHEN C.DTNEG >= PR.DT_INI AND C.DTNEG < PR.DT_FIM + 1 THEN 1 ELSE 0 END AS FL_PERIODO,
           CASE WHEN {{ITEM_ABERTO I}} THEN 1 ELSE 0 END AS FL_ABERTO
    FROM TGFCAB C
    JOIN tops TP ON TP.CODTIPOPER = C.CODTIPOPER
    JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    JOIN TGFPRO P ON P.CODPROD = I.CODPROD
    LEFT JOIN voa VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
    CROSS JOIN prm PR
    WHERE TP.PAPEL = 'ORDEM_COMPRA'
      AND {{FILTRO_EMPRESA C.CODEMP}}
      AND ((C.DTNEG >= PR.DT_INI AND C.DTNEG < PR.DT_FIM + 1) OR {{ITEM_ABERTO I}})
),
occ_lib AS (
    SELECT L.NUCHAVE,
           {{LIB_PEND L}} AS N_LIB_PEND,
           {{LIB_REPROV L}} AS N_LIB_REPROV
    FROM TSILIB L
    WHERE L.TABELA = 'TGFCAB'
      AND L.NUCHAVE IN (SELECT OI.NUNOTA FROM occ_it OI)
    GROUP BY L.NUCHAVE
),
-- Vínculo NATIVO: documentos derivados confirmados (TGFVAR). Só a DATA é usada; a quantidade
-- atendida vem de TGFITE.QTDENTREGUE (registro do sistema, pode refletir customização).
occ_var AS (
    SELECT V.NUNOTAORIG, V.SEQUENCIAORIG,
           COUNT(DISTINCT V.NUNOTA) AS N_DERIV,
           MAX(TRUNC(N.DTNEG)) AS DT_ULT_DERIV
    FROM TGFVAR V
    JOIN TGFCAB N ON N.NUNOTA = V.NUNOTA
    WHERE N.STATUSNOTA = 'L'
      AND V.NUNOTA <> V.NUNOTAORIG
      AND V.NUNOTAORIG IN (SELECT OI.NUNOTA FROM occ_it OI)
    GROUP BY V.NUNOTAORIG, V.SEQUENCIAORIG
),
-- Vínculo INFERIDO por OS + produto (TOPs ENTRADA_POR_OS). Não comprova vínculo: a mesma entrada
-- pode casar com várias OCs; isso é contado e exibido, nunca somado como recebimento.
occ_os_par AS (
    SELECT O.NUNOTA, O.SEQUENCIA, E.NUNOTA AS NUNOTA_ENT, E.SEQUENCIA AS SEQ_ENT, TRUNC(N.DTNEG) AS DT_ENT
    FROM occ_it O
    JOIN TGFITE E ON E.CODPROD = O.CODPROD AND NULLIF(TRIM(E.AD_OS), '') = O.OS
    JOIN TGFCAB N ON N.NUNOTA = E.NUNOTA
    JOIN tops TE ON TE.CODTIPOPER = N.CODTIPOPER
    WHERE TE.PAPEL = 'ENTRADA_POR_OS'
      AND O.OS IS NOT NULL
      AND N.STATUSNOTA = 'L'
      AND N.DTNEG >= O.DT_NEG
),
occ_os AS (
    SELECT X.NUNOTA, X.SEQUENCIA,
           COUNT(*) AS N_ENT_OS,
           MAX(X.DT_ENT) AS DT_ULT_ENT_OS,
           MAX(X.N_OC_MESMA_ENT) AS MAX_OC_MESMA_ENT
    FROM (SELECT Y.NUNOTA, Y.SEQUENCIA, Y.DT_ENT,
                 COUNT(*) OVER (PARTITION BY Y.NUNOTA_ENT, Y.SEQ_ENT) AS N_OC_MESMA_ENT
          FROM occ_os_par Y) X
    GROUP BY X.NUNOTA, X.SEQUENCIA
),
occ AS (
    SELECT O.NUNOTA, O.SEQUENCIA, O.CODEMP, O.CODTIPOPER, O.DHTIPOPER, O.CODPARC, O.GRUPO_PRECO, O.CODPROD,
           O.STATUSNOTA, O.DT_NEG, O.DT_PREV, O.PENDENTE, O.CANCELADO, O.QTDNEG, O.QTDENT, O.VLRTOT,
           O.UNID_ITEM, O.UNID_PADRAO, O.OS, O.FATOR, O.STATUS_CONV, O.FL_PERIODO, O.FL_ABERTO,
           CASE WHEN O.LT_CAD IS NOT NULL THEN TRUNC(O.DT_NEG + O.LT_CAD) END AS DT_PREV_ESTIMADA,
           NVL(LB.N_LIB_PEND, 0) AS N_LIB_PEND,
           NVL(LB.N_LIB_REPROV, 0) AS N_LIB_REPROV,
           {{SITUACAO_OC O.STATUSNOTA, NVL(LB.N_LIB_PEND, 0), NVL(LB.N_LIB_REPROV, 0)}} AS SITUACAO,
           {{PRAZO_OC O.DT_PREV, JA.DT_BASE}} AS PRAZO,
           {{STATUS_ITEM_OC O.CANCELADO, O.PENDENTE, O.QTDNEG, O.QTDENT}} AS STATUS_ITEM,
           CASE WHEN O.FL_ABERTO = 1 AND O.DT_PREV < JA.DT_BASE THEN JA.DT_BASE - O.DT_PREV END AS DIAS_ATRASO,
           JA.DT_BASE - O.DT_NEG AS IDADE_DIAS,
           CASE WHEN O.DT_NEG < ADD_MONTHS(JA.DT_BASE, -PR.OC_ANTIGA_MESES) THEN 1 ELSE 0 END AS FL_ANTIGA,
           CASE WHEN O.FL_ABERTO = 1 AND O.QTDNEG > 0
                THEN O.VLRTOT * (O.QTDNEG - O.QTDENT) / O.QTDNEG ELSE 0 END AS VLR_SALDO,
           CASE WHEN O.FL_ABERTO = 1 AND O.FATOR IS NOT NULL
                THEN (O.QTDNEG - O.QTDENT) * O.FATOR END AS SALDO_BASE,
           CASE WHEN O.PENDENTE = 'N' AND O.CANCELADO <> 'S' AND O.QTDENT > 0 AND O.QTDENT < O.QTDNEG
                THEN O.QTDNEG - O.QTDENT ELSE 0 END AS SALDO_ENCERRADO_ORIG,
           CASE WHEN O.QTDENT > O.QTDNEG THEN 1 ELSE 0 END AS FL_ACIMA_NEGOCIADO,
           NVL(VA.N_DERIV, 0) AS N_DERIV,
           VA.DT_ULT_DERIV,
           NVL(OSX.N_ENT_OS, 0) AS N_ENT_OS,
           OSX.DT_ULT_ENT_OS,
           NVL(OSX.MAX_OC_MESMA_ENT, 0) AS MAX_OC_MESMA_ENT,
           CASE WHEN NVL(VA.N_DERIV, 0) > 0 THEN 'NATIVO_TGFVAR'
                WHEN NVL(OSX.N_ENT_OS, 0) > 0 AND NVL(OSX.MAX_OC_MESMA_ENT, 0) > 1 THEN 'INFERIDO_OS_COMPARTILHADO'
                WHEN NVL(OSX.N_ENT_OS, 0) > 0 THEN 'INFERIDO_OS'
                WHEN O.QTDENT > 0 THEN 'ATENDIMENTO_SEM_VINCULO'
                ELSE 'SEM_ATENDIMENTO' END AS QUALIDADE_VINC
    FROM occ_it O
    LEFT JOIN occ_lib LB ON LB.NUCHAVE = O.NUNOTA
    LEFT JOIN occ_var VA ON VA.NUNOTAORIG = O.NUNOTA AND VA.SEQUENCIAORIG = O.SEQUENCIA
    LEFT JOIN occ_os OSX ON OSX.NUNOTA = O.NUNOTA AND OSX.SEQUENCIA = O.SEQUENCIA
    CROSS JOIN jan JA
    CROSS JOIN prm PR
)
