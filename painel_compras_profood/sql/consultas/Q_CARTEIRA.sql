-- @consulta Q_CARTEIRA
-- @descricao Indicadores agregados da carteira de OC em blocos (uma linha por bloco+chave).
--            N_AUX: ABERTO = itens com unidade não conciliada; PONTUALIDADE/VINCULO/QUALIDADE = 0.
-- @params FLUXO
WITH {{PRM}},
{{TOPS}},
{{FRAGMENTOS calendario unidades oc_carteira}},
occ_fx AS (
    SELECT O.NUNOTA, O.VLR_SALDO,
           CASE WHEN O.IDADE_DIAS <= 15 THEN '1_0_15'
                WHEN O.IDADE_DIAS <= 30 THEN '2_16_30'
                WHEN O.IDADE_DIAS <= 60 THEN '3_31_60'
                WHEN O.IDADE_DIAS <= 180 THEN '4_61_180'
                ELSE '5_181_MAIS' END AS FAIXA
    FROM occ O
    WHERE O.FL_ABERTO = 1
),
-- Indicador APROXIMADO (não é OTIF): itens confirmados com previsão no período e já vencida.
occ_pont AS (
    SELECT O.NUNOTA, O.VLRTOT,
           CASE WHEN O.STATUS_ITEM = 'ATENDIDA_INTEGRAL' AND O.N_DERIV > 0
                     AND O.DT_ULT_DERIV <= O.DT_PREV + PR.TOLERANCIA_ATRASO_DIAS THEN 'INTEGRAL_NO_PRAZO'
                WHEN O.STATUS_ITEM = 'ATENDIDA_INTEGRAL' AND O.N_DERIV > 0 THEN 'INTEGRAL_FORA_PRAZO'
                WHEN O.STATUS_ITEM = 'ATENDIDA_INTEGRAL' THEN 'EXCLUIDO_SEM_DATA_CONFIAVEL'
                WHEN O.STATUS_ITEM IN ('ENCERRADA_COM_SALDO', 'ENCERRADA_SEM_ATENDIMENTO') THEN 'ENCERRADA_SEM_INTEGRAL'
                ELSE 'NAO_ATENDIDA_VENCIDA' END AS CLASSE
    FROM occ O
    CROSS JOIN prm PR
    CROSS JOIN jan JA
    WHERE O.SITUACAO = 'CONFIRMADA'
      AND O.CANCELADO <> 'S'
      AND O.QTDNEG > 0
      AND O.DT_PREV >= PR.DT_INI AND O.DT_PREV < PR.DT_FIM + 1
      AND O.DT_PREV < JA.DT_BASE
),
occ_q AS (
    SELECT 'OC_SEM_PREVISAO' AS CHAVE, O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.PRAZO = 'SEM_PREVISAO'
    UNION ALL SELECT 'UNIDADE_NAO_CONCILIADA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.FATOR IS NULL
    UNION ALL SELECT 'OC_ANTIGA_ABERTA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.FL_ANTIGA = 1
    UNION ALL SELECT 'NAO_CONFIRMADA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.SITUACAO = 'NAO_CONFIRMADA'
    UNION ALL SELECT 'APROVACAO_NAO_DETERMINADA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.SITUACAO = 'APROVACAO_NAO_DETERMINADA'
    UNION ALL SELECT 'ACIMA_NEGOCIADO', O.NUNOTA FROM occ O WHERE O.FL_ACIMA_NEGOCIADO = 1
    UNION ALL SELECT 'ENCERRADA_COM_SALDO', O.NUNOTA FROM occ O WHERE O.FL_PERIODO = 1 AND O.STATUS_ITEM = 'ENCERRADA_COM_SALDO'
    UNION ALL SELECT 'ENTRADA_OS_COMPARTILHADA', O.NUNOTA FROM occ O WHERE O.MAX_OC_MESMA_ENT > 1
    UNION ALL SELECT 'TOP_PRECO_SEPARADO_ABERTA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.GRUPO_PRECO = 'SEPARADO'
),
blocos AS (
    SELECT 'ABERTO' AS BLOCO, O.SITUACAO AS CHAVE, O.PRAZO AS CHAVE2,
           COUNT(DISTINCT O.NUNOTA) AS N_OCS, COUNT(*) AS N_ITENS, SUM(O.VLR_SALDO) AS VLR,
           SUM(CASE WHEN O.FATOR IS NULL THEN 1 ELSE 0 END) AS N_AUX
    FROM occ O WHERE O.FL_ABERTO = 1
    GROUP BY O.SITUACAO, O.PRAZO
    UNION ALL
    SELECT 'FUNIL', O.STATUS_ITEM, O.SITUACAO,
           COUNT(DISTINCT O.NUNOTA), COUNT(*), SUM(O.VLRTOT), 0
    FROM occ O WHERE O.FL_PERIODO = 1
    GROUP BY O.STATUS_ITEM, O.SITUACAO
    UNION ALL
    SELECT 'AGING', F.FAIXA, '-',
           COUNT(DISTINCT F.NUNOTA), COUNT(*), SUM(F.VLR_SALDO), 0
    FROM occ_fx F
    GROUP BY F.FAIXA
    UNION ALL
    SELECT 'PONTUALIDADE', P.CLASSE, '-',
           COUNT(DISTINCT P.NUNOTA), COUNT(*), SUM(P.VLRTOT), 0
    FROM occ_pont P
    GROUP BY P.CLASSE
    UNION ALL
    SELECT 'VINCULO', O.QUALIDADE_VINC, '-',
           COUNT(DISTINCT O.NUNOTA), COUNT(*), SUM(O.VLRTOT), 0
    FROM occ O WHERE O.FL_PERIODO = 1 AND O.QTDENT > 0
    GROUP BY O.QUALIDADE_VINC
    UNION ALL
    SELECT 'QUALIDADE', Q.CHAVE, '-',
           COUNT(DISTINCT Q.NUNOTA), COUNT(*), 0, 0
    FROM occ_q Q
    GROUP BY Q.CHAVE
)
SELECT B.BLOCO, B.CHAVE, B.CHAVE2, B.N_OCS, B.N_ITENS, ROUND(B.VLR, 2) AS VLR, B.N_AUX,
       TO_CHAR(JA.DT_BASE, 'YYYY-MM-DD') AS DT_BASE,
       JA.SNAPSHOT
FROM blocos B
CROSS JOIN jan JA
ORDER BY B.BLOCO, B.CHAVE, B.CHAVE2
