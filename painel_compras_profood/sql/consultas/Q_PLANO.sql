-- @consulta Q_PLANO
-- @descricao Fila de análise (página limitada). Os totais globais vêm de Q_RESUMO, que usa o MESMO cálculo.
-- @params CALCULO LIMITE_FILA FILTRO_FILA
WITH {{PRM}},
{{TOPS}},
{{FRAGMENTOS calendario janela_consumo unidades consumo produtos estoque compromissos oc_planejamento cotacao preco plano}},
fila AS (
    SELECT PL.*,
           CASE WHEN PR.FILTRO_FILA = 'TODOS' THEN 1
                WHEN PR.FILTRO_FILA = 'ATENCAO'
                     AND (PL.PRIORIDADE IN ('P1_CRITICO', 'P2_RUPTURA_IMINENTE', 'P3_ATENCAO') OR PL.NEC_BRUTA > 0) THEN 1
                WHEN PR.FILTRO_FILA = 'EXCESSO' AND PL.PRIORIDADE IN ('P0_EXCESSO', 'P0_SEM_GIRO') THEN 1
                WHEN PR.FILTRO_FILA = 'REVISAR'
                     AND (PL.PRIORIDADE = 'REVISAR_SEM_GIRO' OR PL.N_NAO_CONC > 0 OR PL.FL_HIST_INSUF = 1
                          OR (PL.NEC_BRUTA > 0 AND PL.PRECO_REF IS NULL) OR PL.N_OC_SEM_PREV > 0
                          OR PL.N_OC_ATRAS > 0 OR PL.FL_LOTE_INVALIDO = 1 OR PL.FL_CONSUMO_NEG = 1) THEN 1
                ELSE 0 END AS NO_FILTRO
    FROM plano PL
    CROSS JOIN prm PR
),
ord AS (
    SELECT F.*,
           COUNT(*) OVER () AS TOTAL_LINHAS,
           ROW_NUMBER() OVER (ORDER BY {{ORDEM_PRIORIDADE F.PRIORIDADE}},
                                       F.T_FALTA_PROJ ASC NULLS LAST,
                                       F.VLR_FALTA_ATUAL DESC NULLS LAST,
                                       F.VLR_NEC_NAO_SOLIC DESC NULLS LAST,
                                       F.CODEMP, F.CODPROD) AS RN
    FROM fila F
    WHERE F.NO_FILTRO = 1
)
SELECT O.RN, O.TOTAL_LINHAS,
       O.CODEMP, O.CODPROD, O.DESCRPROD, O.UNIDADE, O.GRUPO, O.GRUPO_DESCR, O.COD_ANTIGO,
       O.CURVA, O.CURVA_ORIGEM, 'NAO_VALIDADA' AS POLITICA,
       O.PRIORIDADE, O.MOTIVOS,
       ROUND(O.QTD_ESTOQUE, 3) AS QTD_ESTOQUE,
       ROUND(O.QTD_RESERVADO, 3) AS QTD_RESERVADO,
       ROUND(O.QTD_BLOQUEADO, 3) AS QTD_BLOQUEADO,
       ROUND(O.QTD_PEDIDOS, 3) AS QTD_PEDIDOS,
       ROUND(O.QTD_CONFERIDA, 3) AS QTD_CONFERIDA,
       ROUND(O.CMP, 3) AS CMP,
       ROUND(O.EFP, 3) AS EFP,
       ROUND(O.DISPONIVEL, 3) AS DISPONIVEL,
       O.ORIGEM_SERIE,
       TO_CHAR(O.DT_PRIM_CONSUMO, 'YYYY-MM-DD') AS DT_PRIM_CONSUMO,
       O.N_MESES,
       ROUND(O.FRAC_USADA, 4) AS FRAC_USADA,
       ROUND(O.QTD_JANELA, 3) AS QTD_JANELA,
       ROUND(O.QTD_PARCIAL, 3) AS QTD_PARCIAL,
       ROUND(O.MEDIA_SIMPLES, 3) AS MEDIA_SIMPLES,
       ROUND(O.MEDIA_PONDERADA, 3) AS MEDIA_PONDERADA,
       ROUND(O.MEDIA_USADA, 3) AS MEDIA_USADA,
       ROUND(O.DD, 4) AS DD,
       O.FL_HIST_INSUF, O.FL_CONSUMO_NEG, O.FL_SEM_GIRO,
       O.LT, O.FL_LT_PADRAO, O.COB_ALVO,
       ROUND(O.EST_SEG, 3) AS EST_SEG,
       ROUND(O.PONTO_PEDIDO, 3) AS PONTO_PEDIDO,
       ROUND(O.REQUISITO, 3) AS REQUISITO,
       ROUND(O.REQUISITO_SOMA, 3) AS REQUISITO_SOMA,
       ROUND(O.REQUISITO_MAIOR, 3) AS REQUISITO_MAIOR,
       ROUND(O.QTD_OC_CONF, 3) AS QTD_OC_CONF,
       ROUND(O.QTD_OC_CONF_PRAZO, 3) AS QTD_OC_CONF_PRAZO,
       ROUND(O.QTD_OC_CONF_ATRAS, 3) AS QTD_OC_CONF_ATRAS,
       ROUND(O.QTD_OC_CONF_SEMPREV, 3) AS QTD_OC_CONF_SEMPREV,
       ROUND(O.QTD_OC_NAO_CONF, 3) AS QTD_OC_NAO_CONF,
       O.N_OCS_ABERTAS, O.N_OC_ATRAS, O.N_OC_SEM_PREV, O.N_OC_ANTIGA, O.N_OC_TOP_SEP,
       ROUND(O.QTD_COTACAO, 3) AS QTD_COTACAO,
       ROUND(O.POS_CONTRATADA, 3) AS POS_CONTRATADA,
       ROUND(O.COB_FISICA_DIAS, 1) AS COB_FISICA_DIAS,
       ROUND(O.COB_CONTRAT_DIAS, 1) AS COB_CONTRAT_DIAS,
       TO_CHAR(O.DT_PROX_RECEB, 'YYYY-MM-DD') AS DT_PROX_RECEB,
       ROUND(O.QTD_PROX_RECEB, 3) AS QTD_PROX_RECEB,
       O.FL_FALTA_ANTES_RECEB,
       TO_CHAR(O.DT_RECEB_APOS_FALTA, 'YYYY-MM-DD') AS DT_RECEB_APOS_FALTA,
       ROUND(O.QTD_FALTA_ANTES_RECEB, 3) AS QTD_FALTA_ANTES_RECEB,
       ROUND(O.T_FALTA_PROJ, 1) AS T_FALTA_PROJ,
       TO_CHAR(O.DT_FALTA_EST, 'YYYY-MM-DD') AS DT_FALTA_EST,
       ROUND(O.NEC_BRUTA, 3) AS NEC_BRUTA,
       ROUND(O.NEC_SOMA, 3) AS NEC_SOMA,
       ROUND(O.NEC_MAIOR, 3) AS NEC_MAIOR,
       ROUND(O.NEC_EM_OC_NAO_CONF, 3) AS NEC_EM_OC_NAO_CONF,
       ROUND(O.NEC_EM_COTACAO, 3) AS NEC_EM_COTACAO,
       ROUND(O.NEC_NAO_SOLIC, 3) AS NEC_NAO_SOLIC,
       O.AGRUPMIN, O.LOTEMIN, O.FL_LOTE_INVALIDO,
       ROUND(O.QTD_ARRED, 3) AS QTD_ARRED,
       ROUND(O.EXCESSO_ARRED, 3) AS EXCESSO_ARRED,
       ROUND(O.PRECO_REF, 6) AS PRECO_REF,
       TO_CHAR(O.PRECO_REF_DATA, 'YYYY-MM-DD') AS PRECO_REF_DATA,
       O.PRECO_REF_NUNOTA, O.PRECO_REF_TOP,
       ROUND(O.PRECO_SEP, 6) AS PRECO_SEP,
       TO_CHAR(O.PRECO_SEP_DATA, 'YYYY-MM-DD') AS PRECO_SEP_DATA,
       ROUND(O.VLR_FALTA_ATUAL, 2) AS VLR_FALTA_ATUAL,
       ROUND(O.VLR_NEC_NAO_SOLIC, 2) AS VLR_NEC_NAO_SOLIC,
       O.ESTMIN_CAD, O.FL_CONSIGNADO,
       O.N_CONS_NAO_CONC, O.N_PED_NAO_CONC, O.N_OC_NAO_CONC, O.N_COT_NAO_CONC, O.N_NAO_CONC,
       ROUND(O.VALOR_ABC, 2) AS VALOR_ABC
FROM ord O
CROSS JOIN prm PR
WHERE O.RN <= PR.LIMITE_FILA
ORDER BY O.RN
