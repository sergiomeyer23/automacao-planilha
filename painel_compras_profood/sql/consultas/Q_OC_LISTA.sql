-- @consulta Q_OC_LISTA
-- @descricao Itens de OC com saldo aberto (sem corte de data), com situação, prazo e qualidade do vínculo.
--            CODPROD_FILTRO > 0 = detalhe de um produto. Lista limitada; totais por janela analítica.
-- @params FLUXO LIMITE_OC FILTRO_OC CODPROD_FILTRO
WITH {{PRM}},
{{TOPS}},
{{FRAGMENTOS calendario unidades oc_carteira}},
lista AS (
    SELECT O.*, PA.NOMEPARC AS FORNECEDOR, T.DESCROPER AS DESCR_TOP, PD.DESCRPROD
    FROM occ O
    JOIN TGFPRO PD ON PD.CODPROD = O.CODPROD
    LEFT JOIN TGFPAR PA ON PA.CODPARC = O.CODPARC
    LEFT JOIN TGFTOP T ON T.CODTIPOPER = O.CODTIPOPER AND T.DHALTER = O.DHTIPOPER
    CROSS JOIN prm PR
    WHERE O.FL_ABERTO = 1
      AND (PR.CODPROD_FILTRO = 0 OR O.CODPROD = PR.CODPROD_FILTRO)
      AND (PR.FILTRO_OC = 'TODAS'
           OR (PR.FILTRO_OC = 'ATRASADAS' AND O.PRAZO = 'ATRASADA')
           OR (PR.FILTRO_OC = 'SEM_PREVISAO' AND O.PRAZO = 'SEM_PREVISAO')
           OR (PR.FILTRO_OC = 'NAO_CONFIRMADAS' AND O.SITUACAO <> 'CONFIRMADA')
           OR (PR.FILTRO_OC = 'ANTIGAS' AND O.FL_ANTIGA = 1))
),
ord AS (
    SELECT L.*,
           COUNT(*) OVER () AS TOTAL_LINHAS,
           SUM(L.VLR_SALDO) OVER () AS TOTAL_VLR_SALDO,
           ROW_NUMBER() OVER (ORDER BY L.DIAS_ATRASO DESC NULLS LAST, L.VLR_SALDO DESC, L.NUNOTA, L.SEQUENCIA) AS RN
    FROM lista L
)
SELECT O.RN, O.TOTAL_LINHAS, ROUND(O.TOTAL_VLR_SALDO, 2) AS TOTAL_VLR_SALDO,
       O.NUNOTA, O.SEQUENCIA, O.CODEMP, O.CODTIPOPER, O.DESCR_TOP, O.GRUPO_PRECO,
       O.CODPARC, O.FORNECEDOR, O.CODPROD, O.DESCRPROD,
       O.UNID_ITEM, O.UNID_PADRAO, ROUND(O.FATOR, 6) AS FATOR, O.STATUS_CONV,
       ROUND(O.QTDNEG, 3) AS QTDNEG, ROUND(O.QTDENT, 3) AS QTDENT,
       ROUND(O.QTDNEG - O.QTDENT, 3) AS SALDO_ORIG,
       ROUND(O.SALDO_BASE, 3) AS SALDO_BASE,
       ROUND(O.VLR_SALDO, 2) AS VLR_SALDO,
       TO_CHAR(O.DT_NEG, 'YYYY-MM-DD') AS DT_NEG,
       TO_CHAR(O.DT_PREV, 'YYYY-MM-DD') AS DT_PREV,
       TO_CHAR(O.DT_PREV_ESTIMADA, 'YYYY-MM-DD') AS DT_PREV_ESTIMADA,
       O.PRAZO, O.DIAS_ATRASO, O.IDADE_DIAS, O.FL_ANTIGA,
       O.STATUSNOTA, O.SITUACAO, O.N_LIB_PEND, O.N_LIB_REPROV,
       O.STATUS_ITEM, O.OS, O.QUALIDADE_VINC, O.N_DERIV,
       TO_CHAR(O.DT_ULT_DERIV, 'YYYY-MM-DD') AS DT_ULT_DERIV,
       O.N_ENT_OS, O.MAX_OC_MESMA_ENT,
       TO_CHAR(O.DT_ULT_ENT_OS, 'YYYY-MM-DD') AS DT_ULT_ENT_OS,
       'NAO_VALIDADA' AS POLITICA
FROM ord O
CROSS JOIN prm PR
WHERE O.RN <= PR.LIMITE_OC
ORDER BY O.RN
