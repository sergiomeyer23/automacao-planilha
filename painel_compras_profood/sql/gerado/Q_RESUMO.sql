-- Binds na ordem dos '?': CODEMP:I, DIAS_MES:I, MESES_MEDIA:I, MES_PARCIAL:I, MEDIA_MODO:I, MIN_MESES_HIST:I, LEADTIME_DEFAULT:I, COBERTURA_ALVO_A:I, COBERTURA_ALVO_B:I, COBERTURA_ALVO_C:I, COBERTURA_SEM_CURVA:I, POLITICA_SEGURANCA:I, SEGURANCA_PCT_LT:I, MARGEM_ATENCAO_DIAS:I, COBERTURA_MAX_DIAS:I, FONTE_COMPROMISSO:I, DESCONTA_BLOQUEADO:I, REGRA_PREVISAO_FIRME:I, LOTE_MULTIPLO:I, ABC_CALCULADA:I, ABC_LIMITE_A:I, ABC_LIMITE_B:I, OC_ANTIGA_MESES:I

WITH prm AS (
    SELECT CAST(TO_NUMBER(?) AS INTEGER) AS CODEMP,
           TO_NUMBER(?) / 10000 AS DIAS_MES,
           CAST(TO_NUMBER(?) AS INTEGER) AS MESES_MEDIA,
           CAST(TO_NUMBER(?) AS INTEGER) AS MES_PARCIAL,
           CAST(TO_NUMBER(?) AS INTEGER) AS MEDIA_MODO,
           CAST(TO_NUMBER(?) AS INTEGER) AS MIN_MESES_HIST,
           CAST(TO_NUMBER(?) AS INTEGER) AS LEADTIME_DEFAULT,
           CAST(TO_NUMBER(?) AS INTEGER) AS COBERTURA_ALVO_A,
           CAST(TO_NUMBER(?) AS INTEGER) AS COBERTURA_ALVO_B,
           CAST(TO_NUMBER(?) AS INTEGER) AS COBERTURA_ALVO_C,
           CAST(TO_NUMBER(?) AS INTEGER) AS COBERTURA_SEM_CURVA,
           CAST(TO_NUMBER(?) AS INTEGER) AS POLITICA_SEGURANCA,
           TO_NUMBER(?) / 10000 AS SEGURANCA_PCT_LT,
           CAST(TO_NUMBER(?) AS INTEGER) AS MARGEM_ATENCAO_DIAS,
           CAST(TO_NUMBER(?) AS INTEGER) AS COBERTURA_MAX_DIAS,
           CAST(TO_NUMBER(?) AS INTEGER) AS FONTE_COMPROMISSO,
           CAST(TO_NUMBER(?) AS INTEGER) AS DESCONTA_BLOQUEADO,
           CAST(TO_NUMBER(?) AS INTEGER) AS REGRA_PREVISAO_FIRME,
           CAST(TO_NUMBER(?) AS INTEGER) AS LOTE_MULTIPLO,
           CAST(TO_NUMBER(?) AS INTEGER) AS ABC_CALCULADA,
           TO_NUMBER(?) / 10000 AS ABC_LIMITE_A,
           TO_NUMBER(?) / 10000 AS ABC_LIMITE_B,
           CAST(TO_NUMBER(?) AS INTEGER) AS OC_ANTIGA_MESES
    FROM DUAL
),
