    UNION ALL SELECT 200 AS CODTIPOPER, 'ENTRADA_POR_OS' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
),
-- Data-base do cálculo: data do BANCO (SYSDATE), nunca do navegador.
-- A posição de estoque (TGFEST) é sempre a atual; por isso a data-base é hoje.
jan AS (
    SELECT TRUNC(SYSDATE) AS DT_BASE,
           TRUNC(SYSDATE, 'MM') AS M0,
           TO_CHAR(SYSDATE, 'DD/MM/YYYY HH24:MI') AS SNAPSHOT
    FROM DUAL
),
-- Janela de consumo: MESES_MEDIA meses completos antes do mês da data-base.
-- HORIZ_INI: 12 meses antes da janela, só para saber se o produto já tinha consumo (série antiga).
-- FRAC: fração decorrida do mês corrente até ONTEM (usada só se MES_PARCIAL = 1).
janc AS (
    SELECT JA.DT_BASE, JA.M0,
           ADD_MONTHS(JA.M0, -PR.MESES_MEDIA) AS INI,
           ADD_MONTHS(JA.M0, -PR.MESES_MEDIA - 12) AS HORIZ_INI,
           EXTRACT(YEAR FROM JA.M0) * 12 + EXTRACT(MONTH FROM JA.M0) AS IDX_M0,
           PR.MESES_MEDIA AS N,
           CASE WHEN PR.MES_PARCIAL = 1
                THEN (JA.DT_BASE - JA.M0) / (ADD_MONTHS(JA.M0, 1) - JA.M0)
                ELSE 0 END AS FRAC
    FROM jan JA
    CROSS JOIN prm PR
),
-- Regras de conversão ativas, agrupadas ANTES do join (nunca multiplicam linhas).
-- Mais de uma regra distinta para o mesmo produto+unidade = AMBIGUA (não converte).
voa AS (
    SELECT V.CODPROD, V.CODVOL,
           MAX(V.DIVIDEMULTIPLICA) AS DM,
           MAX(V.QUANTIDADE) AS QC,
           COUNT(DISTINCT NVL(V.DIVIDEMULTIPLICA, '-') || '|' || NVL(CAST(V.QUANTIDADE AS VARCHAR(40)), '-')) AS N_REGRAS
    FROM TGFVOA V
    WHERE NVL(V.ATIVO, 'S') = 'S'
    GROUP BY V.CODPROD, V.CODVOL
),
-- Movimentos de consumo líquido (papéis CONSUMO, DEVOLUCAO e PERDA da config) em notas confirmadas.
-- Limites de data com horário: >= início e < data-base (o dia da data-base fica de fora).
-- Item sem conversão confiável fica com FATOR NULL e é EXCLUÍDO das quantidades (contado à parte).
cmov AS (
    SELECT C.CODEMP, I.CODPROD, TP.PAPEL,
           TRUNC(C.DTNEG) AS DT,
           EXTRACT(YEAR FROM C.DTNEG) * 12 + EXTRACT(MONTH FROM C.DTNEG) AS IDX_MES,
           NVL(I.QTDNEG, 0) AS QTD_ORIG,
           NVL(I.VLRTOT, 0) AS VLR,
           (CASE WHEN I.CODVOL = P.CODVOL THEN 1
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QC > 0 THEN VO.QC
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QC > 0 THEN 1 / VO.QC
 END) AS FATOR
    FROM TGFCAB C
    JOIN tops TP ON TP.CODTIPOPER = C.CODTIPOPER
    JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    JOIN TGFPRO P ON P.CODPROD = I.CODPROD
    LEFT JOIN voa VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
    CROSS JOIN prm PR
    CROSS JOIN janc JC
    WHERE TP.PAPEL IN ('CONSUMO', 'DEVOLUCAO', 'PERDA')
      AND C.STATUSNOTA = 'L'
      AND NVL(I.CANCELADO, 'N') <> 'S'
      AND C.DTNEG >= JC.HORIZ_INI
      AND C.DTNEG < JC.DT_BASE
      AND (PR.CODEMP = 0 OR C.CODEMP = PR.CODEMP)
),
cons_mes AS (
    SELECT M.CODEMP, M.CODPROD, M.IDX_MES,
           SUM(CASE WHEN M.FATOR IS NULL THEN 0
                    WHEN M.PAPEL = 'DEVOLUCAO' THEN -M.QTD_ORIG * M.FATOR
                    ELSE M.QTD_ORIG * M.FATOR END) AS QTD,
           SUM(CASE WHEN M.FATOR IS NOT NULL AND M.PAPEL = 'CONSUMO' THEN M.QTD_ORIG * M.FATOR ELSE 0 END) AS QTD_SAIDA,
           SUM(CASE WHEN M.FATOR IS NOT NULL AND M.PAPEL = 'DEVOLUCAO' THEN M.QTD_ORIG * M.FATOR ELSE 0 END) AS QTD_DEVOL,
           SUM(CASE WHEN M.FATOR IS NOT NULL AND M.PAPEL = 'PERDA' THEN M.QTD_ORIG * M.FATOR ELSE 0 END) AS QTD_PERDA,
           SUM(CASE WHEN M.PAPEL = 'CONSUMO' THEN M.VLR WHEN M.PAPEL = 'DEVOLUCAO' THEN -M.VLR ELSE 0 END) AS VLR_FAT,
           SUM(CASE WHEN M.FATOR IS NULL THEN 1 ELSE 0 END) AS N_NAO_CONC
    FROM cmov M
    GROUP BY M.CODEMP, M.CODPROD, M.IDX_MES
),
-- Início da série = mês do primeiro CONSUMO dentro do horizonte (fonte demonstrada: as próprias notas).
serie AS (
    SELECT M.CODEMP, M.CODPROD, MIN(M.IDX_MES) AS IDX_PRIM, MIN(M.DT) AS DT_PRIM
    FROM cmov M
    WHERE M.PAPEL = 'CONSUMO'
    GROUP BY M.CODEMP, M.CODPROD
),
med0 AS (
    SELECT S.CODEMP, S.CODPROD, S.IDX_PRIM, S.DT_PRIM,
           CASE WHEN S.IDX_PRIM < JC.IDX_M0 - JC.N THEN 'ANTIGO'
                WHEN S.IDX_PRIM < JC.IDX_M0 THEN 'NOVO'
                ELSE 'SO_MES_ATUAL' END AS ORIGEM_SERIE,
           CASE WHEN S.IDX_PRIM < JC.IDX_M0 - JC.N THEN JC.N
                WHEN S.IDX_PRIM < JC.IDX_M0 THEN JC.IDX_M0 - S.IDX_PRIM
                ELSE 0 END AS N_MESES
    FROM serie S
    CROSS JOIN janc JC
),
-- Somatórios só sobre os meses da série do produto (idade 1..N_MESES); mês sem movimento conta como zero.
cons_ag AS (
    SELECT CM.CODEMP, CM.CODPROD,
           SUM(CASE WHEN JC.IDX_M0 - CM.IDX_MES BETWEEN 1 AND NVL(M0.N_MESES, 0) THEN CM.QTD ELSE 0 END) AS QTD_JANELA,
           SUM(CASE WHEN CM.IDX_MES = JC.IDX_M0 THEN CM.QTD ELSE 0 END) AS QTD_PARCIAL,
           SUM(CASE WHEN JC.IDX_M0 - CM.IDX_MES BETWEEN 1 AND LEAST(NVL(M0.N_MESES, 0), 3) THEN CM.QTD ELSE 0 END) AS QTD_3M,
           SUM(CASE WHEN JC.IDX_M0 - CM.IDX_MES BETWEEN 1 AND NVL(M0.N_MESES, 0)
                    THEN CM.QTD * ((CASE WHEN JC.IDX_M0 - CM.IDX_MES <= 3 THEN 0.5 / 3 ELSE 0 END)
                                 + (CASE WHEN JC.IDX_M0 - CM.IDX_MES <= 6 THEN 0.3 / 6 ELSE 0 END)
                                 + 0.2 / JC.N)
                    ELSE 0 END) AS POND_NUM,
           SUM(CASE WHEN JC.IDX_M0 - CM.IDX_MES BETWEEN 1 AND JC.N THEN CM.N_NAO_CONC
                    WHEN CM.IDX_MES = JC.IDX_M0 AND PR.MES_PARCIAL = 1 THEN CM.N_NAO_CONC
                    ELSE 0 END) AS N_CONS_NAO_CONC,
           SUM(CASE WHEN JC.IDX_M0 - CM.IDX_MES BETWEEN 1 AND JC.N THEN CM.VLR_FAT ELSE 0 END) AS VLR_FAT_JANELA
    FROM cons_mes CM
    LEFT JOIN med0 M0 ON M0.CODEMP = CM.CODEMP AND M0.CODPROD = CM.CODPROD
    CROSS JOIN janc JC
    CROSS JOIN prm PR
    GROUP BY CM.CODEMP, CM.CODPROD
),
med AS (
    SELECT K.CODEMP, K.CODPROD,
           NVL(M0.ORIGEM_SERIE, 'SEM_CONSUMO') AS ORIGEM_SERIE,
           M0.DT_PRIM AS DT_PRIM_CONSUMO,
           NVL(M0.N_MESES, 0) AS N_MESES,
           CASE WHEN PR.MES_PARCIAL = 1 AND M0.CODPROD IS NOT NULL THEN JC.FRAC ELSE 0 END AS FRAC_USADA,
           NVL(CA.QTD_JANELA, 0) AS QTD_JANELA,
           NVL(CA.QTD_PARCIAL, 0) AS QTD_PARCIAL,
           NVL(CA.QTD_3M, 0) AS QTD_3M,
           NVL(CA.POND_NUM, 0) AS POND_NUM,
           NVL(CA.N_CONS_NAO_CONC, 0) AS N_CONS_NAO_CONC,
           NVL(CA.VLR_FAT_JANELA, 0) AS VLR_FAT_JANELA
    FROM (SELECT CA0.CODEMP, CA0.CODPROD FROM cons_ag CA0
          UNION
          SELECT MZ.CODEMP, MZ.CODPROD FROM med0 MZ) K
    LEFT JOIN med0 M0 ON M0.CODEMP = K.CODEMP AND M0.CODPROD = K.CODPROD
    LEFT JOIN cons_ag CA ON CA.CODEMP = K.CODEMP AND CA.CODPROD = K.CODPROD
    CROSS JOIN prm PR
    CROSS JOIN janc JC
),
med2 AS (
    SELECT MD.CODEMP, MD.CODPROD, MD.ORIGEM_SERIE, MD.DT_PRIM_CONSUMO, MD.N_MESES, MD.FRAC_USADA,
           MD.QTD_JANELA, MD.QTD_PARCIAL, MD.QTD_3M, MD.N_CONS_NAO_CONC, MD.VLR_FAT_JANELA,
           CASE WHEN MD.N_MESES + MD.FRAC_USADA > 0
                THEN (MD.QTD_JANELA + CASE WHEN MD.FRAC_USADA > 0 THEN MD.QTD_PARCIAL ELSE 0 END)
                     / (MD.N_MESES + MD.FRAC_USADA) END AS MEDIA_SIMPLES,
           CASE WHEN MD.N_MESES >= 1
                THEN MD.POND_NUM / (0.5 / 3 * LEAST(MD.N_MESES, 3) + 0.3 / 6 * LEAST(MD.N_MESES, 6)
                                    + 0.2 / JC.N * MD.N_MESES) END AS MEDIA_PONDERADA,
           CASE WHEN MD.N_MESES >= 1 THEN MD.QTD_3M / LEAST(MD.N_MESES, 3) END AS MEDIA_3M
    FROM med MD
    CROSS JOIN janc JC
),
med3 AS (
    SELECT M2.CODEMP, M2.CODPROD, M2.ORIGEM_SERIE, M2.DT_PRIM_CONSUMO, M2.N_MESES, M2.FRAC_USADA,
           M2.QTD_JANELA, M2.QTD_PARCIAL, M2.QTD_3M, M2.N_CONS_NAO_CONC, M2.VLR_FAT_JANELA,
           M2.MEDIA_SIMPLES, M2.MEDIA_PONDERADA, M2.MEDIA_3M,
           CASE WHEN PR.MEDIA_MODO = 1 THEN M2.MEDIA_PONDERADA ELSE M2.MEDIA_SIMPLES END AS MEDIA_CALC,
           CASE WHEN M2.ORIGEM_SERIE IN ('NOVO', 'SO_MES_ATUAL') AND M2.N_MESES + M2.FRAC_USADA < PR.MIN_MESES_HIST
                THEN 1 ELSE 0 END AS FL_HIST_INSUF
    FROM med2 M2
    CROSS JOIN prm PR
),
prod AS (
    SELECT P.CODPROD, P.DESCRPROD, P.CODVOL AS UNIDADE,
           P.CODGRUPOPROD AS GRUPO, G.DESCRGRUPOPROD AS GRUPO_DESCR,
           CASE WHEN P.LEADTIME > 0 THEN P.LEADTIME END AS LT_CAD,
           CASE WHEN P.ESTMIN > 0 THEN P.ESTMIN END AS ESTMIN_CAD,
           P.AGRUPMIN AS AGRUPMIN,
           P.LOTECOMPMINIMO AS LOTEMIN,
           CASE WHEN NVL(P.CODPARCCONSIG, 0) > 0 THEN 1 ELSE 0 END AS FL_CONSIGNADO,
           CAST(NULL AS VARCHAR(60)) AS COD_ANTIGO
    FROM TGFPRO P
    LEFT JOIN TGFGRU G ON G.CODGRUPOPROD = P.CODGRUPOPROD
    WHERE P.ATIVO = 'S'
),
-- Estoque físico atual por empresa+produto. Locais excluídos vêm da configuração do build.
est AS (
    SELECT E.CODEMP, E.CODPROD,
           SUM(NVL(E.ESTOQUE, 0)) AS QTD_ESTOQUE,
           SUM(NVL(E.RESERVADO, 0)) AS QTD_RESERVADO,
           SUM(NVL(E.WMSBLOQUEADO, 0)) AS QTD_BLOQUEADO
    FROM TGFEST E
    CROSS JOIN prm PR
    WHERE (PR.CODEMP = 0 OR E.CODEMP = PR.CODEMP)
      AND E.CODLOCAL NOT IN (1030000, 2030000)
    GROUP BY E.CODEMP, E.CODPROD
),
-- Pedidos/empenhos pendentes (TOPs do papel EMPENHO). Saldo = QTDNEG - QTDENTREGUE.
-- QTDCONFERIDA é só informativa (o original a descontava; ver PARAMETROS_A_APROVAR.md).
cmp_it AS (
    SELECT C.CODEMP, I.CODPROD,
           NVL(I.QTDNEG, 0) - NVL(I.QTDENTREGUE, 0) AS SALDO_ORIG,
           NVL(I.QTDCONFERIDA, 0) AS CONF_ORIG,
           (CASE WHEN I.CODVOL = P.CODVOL THEN 1
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QC > 0 THEN VO.QC
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QC > 0 THEN 1 / VO.QC
 END) AS FATOR
    FROM TGFCAB C
    JOIN tops TP ON TP.CODTIPOPER = C.CODTIPOPER
    JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    JOIN TGFPRO P ON P.CODPROD = I.CODPROD
    LEFT JOIN voa VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
    CROSS JOIN prm PR
    WHERE TP.PAPEL = 'EMPENHO'
      AND I.PENDENTE = 'S'
      AND (NVL(I.PENDENTE, 'S') = 'S' AND NVL(I.CANCELADO, 'N') <> 'S' AND NVL(I.QTDNEG, 0) > NVL(I.QTDENTREGUE, 0))
      AND (PR.CODEMP = 0 OR C.CODEMP = PR.CODEMP)
),
cmp AS (
    SELECT X.CODEMP, X.CODPROD,
           SUM(CASE WHEN X.FATOR IS NULL THEN 0 ELSE X.SALDO_ORIG * X.FATOR END) AS QTD_PEDIDOS,
           SUM(CASE WHEN X.FATOR IS NULL THEN 0 ELSE X.CONF_ORIG * X.FATOR END) AS QTD_CONFERIDA,
           SUM(CASE WHEN X.FATOR IS NULL THEN 1 ELSE 0 END) AS N_PED_NAO_CONC
    FROM cmp_it X
    GROUP BY X.CODEMP, X.CODPROD
),
-- Itens de OC com saldo aberto, SEM corte de data: OC antiga ainda aberta continua visível (sinalizada).
oc_it AS (
    SELECT C.NUNOTA, I.SEQUENCIA, C.CODEMP, C.CODTIPOPER, TP.GRUPO_PRECO, I.CODPROD, C.STATUSNOTA,
           TRUNC(C.DTNEG) AS DT_NEG,
           TRUNC(C.DTPREVENT) AS DT_PREV,
           NVL(I.QTDNEG, 0) AS QTDNEG,
           NVL(I.QTDENTREGUE, 0) AS QTDENT,
           (CASE WHEN I.CODVOL = P.CODVOL THEN 1
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QC > 0 THEN VO.QC
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QC > 0 THEN 1 / VO.QC
 END) AS FATOR
    FROM TGFCAB C
    JOIN tops TP ON TP.CODTIPOPER = C.CODTIPOPER
    JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    JOIN TGFPRO P ON P.CODPROD = I.CODPROD
    LEFT JOIN voa VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
    CROSS JOIN prm PR
    WHERE TP.PAPEL = 'ORDEM_COMPRA'
      AND (NVL(I.PENDENTE, 'S') = 'S' AND NVL(I.CANCELADO, 'N') <> 'S' AND NVL(I.QTDNEG, 0) > NVL(I.QTDENTREGUE, 0))
      AND (PR.CODEMP = 0 OR C.CODEMP = PR.CODEMP)
),
-- Liberações agregadas por nota ANTES do join (o histórico de liberações não duplica itens).
oc_lib AS (
    SELECT L.NUCHAVE,
           SUM(CASE WHEN L.DHLIB IS NULL AND NVL(L.REPROVADO, 'N') <> 'S' THEN 1 ELSE 0 END) AS N_LIB_PEND,
           SUM(CASE WHEN NVL(L.REPROVADO, 'N') = 'S' THEN 1 ELSE 0 END) AS N_LIB_REPROV
    FROM TSILIB L
    WHERE L.TABELA = 'TGFCAB'
      AND L.NUCHAVE IN (SELECT OI.NUNOTA FROM oc_it OI)
    GROUP BY L.NUCHAVE
),
oc_ab AS (
    SELECT O.NUNOTA, O.SEQUENCIA, O.CODEMP, O.CODTIPOPER, O.GRUPO_PRECO, O.CODPROD, O.DT_NEG, O.DT_PREV, O.FATOR,
           (CASE WHEN O.STATUSNOTA = 'L' AND NVL(LB.N_LIB_PEND, 0) = 0 AND NVL(LB.N_LIB_REPROV, 0) = 0 THEN 'CONFIRMADA'
      WHEN O.STATUSNOTA = 'L' THEN 'APROVACAO_NAO_DETERMINADA'
      ELSE 'NAO_CONFIRMADA'
 END) AS SITUACAO,
           (CASE WHEN O.DT_PREV IS NULL THEN 'SEM_PREVISAO'
      WHEN O.DT_PREV < JA.DT_BASE THEN 'ATRASADA'
      ELSE 'NO_PRAZO'
 END) AS PRAZO,
           CASE WHEN O.FATOR IS NULL THEN NULL ELSE (O.QTDNEG - O.QTDENT) * O.FATOR END AS SALDO_BASE,
           CASE WHEN O.DT_NEG < ADD_MONTHS(JA.DT_BASE, -PR.OC_ANTIGA_MESES) THEN 1 ELSE 0 END AS FL_ANTIGA
    FROM oc_it O
    LEFT JOIN oc_lib LB ON LB.NUCHAVE = O.NUNOTA
    CROSS JOIN jan JA
    CROSS JOIN prm PR
),
oc_pos AS (
    SELECT A.CODEMP, A.CODPROD,
           SUM(CASE WHEN A.SITUACAO = 'CONFIRMADA' THEN NVL(A.SALDO_BASE, 0) ELSE 0 END) AS QTD_OC_CONF,
           SUM(CASE WHEN A.SITUACAO = 'CONFIRMADA' AND A.PRAZO = 'NO_PRAZO' THEN NVL(A.SALDO_BASE, 0) ELSE 0 END) AS QTD_OC_CONF_PRAZO,
           SUM(CASE WHEN A.SITUACAO = 'CONFIRMADA' AND A.PRAZO = 'ATRASADA' THEN NVL(A.SALDO_BASE, 0) ELSE 0 END) AS QTD_OC_CONF_ATRAS,
           SUM(CASE WHEN A.SITUACAO = 'CONFIRMADA' AND A.PRAZO = 'SEM_PREVISAO' THEN NVL(A.SALDO_BASE, 0) ELSE 0 END) AS QTD_OC_CONF_SEMPREV,
           SUM(CASE WHEN A.SITUACAO <> 'CONFIRMADA' THEN NVL(A.SALDO_BASE, 0) ELSE 0 END) AS QTD_OC_NAO_CONF,
           COUNT(DISTINCT A.NUNOTA) AS N_OCS_ABERTAS,
           SUM(CASE WHEN A.FATOR IS NULL THEN 1 ELSE 0 END) AS N_OC_NAO_CONC,
           SUM(CASE WHEN A.PRAZO = 'SEM_PREVISAO' THEN 1 ELSE 0 END) AS N_OC_SEM_PREV,
           SUM(CASE WHEN A.PRAZO = 'ATRASADA' THEN 1 ELSE 0 END) AS N_OC_ATRAS,
           SUM(A.FL_ANTIGA) AS N_OC_ANTIGA,
           SUM(CASE WHEN A.GRUPO_PRECO = 'SEPARADO' THEN 1 ELSE 0 END) AS N_OC_TOP_SEP
    FROM oc_ab A
    GROUP BY A.CODEMP, A.CODPROD
),
-- Recebimentos com data confiável: OC confirmada, previsão informada >= data-base e unidade conciliada.
rec AS (
    SELECT A.CODEMP, A.CODPROD, A.DT_PREV, SUM(A.SALDO_BASE) AS QTD
    FROM oc_ab A
    WHERE A.SITUACAO = 'CONFIRMADA' AND A.PRAZO = 'NO_PRAZO' AND A.SALDO_BASE IS NOT NULL
    GROUP BY A.CODEMP, A.CODPROD, A.DT_PREV
),
rec2 AS (
    SELECT R.CODEMP, R.CODPROD, R.DT_PREV, R.QTD,
           NVL(SUM(R.QTD) OVER (PARTITION BY R.CODEMP, R.CODPROD ORDER BY R.DT_PREV
                                ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING), 0) AS ACUM_ANTES,
           ROW_NUMBER() OVER (PARTITION BY R.CODEMP, R.CODPROD ORDER BY R.DT_PREV) AS ORDEM_REC
    FROM rec R
),
-- Necessidade em negociação. Só existe se houver TOPs no papel COTACAO (config).
-- Saldo = QTDNEG - QTDENTREGUE: ao virar OC o atendimento sai da cotação e entra na OC
-- (sem desconto duplo). Sem TOP mapeada, este bloco não retorna linhas e o painel mostra "não mapeado".
cot_it AS (
    SELECT C.CODEMP, I.CODPROD,
           NVL(I.QTDNEG, 0) - NVL(I.QTDENTREGUE, 0) AS SALDO_ORIG,
           (CASE WHEN I.CODVOL = P.CODVOL THEN 1
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QC > 0 THEN VO.QC
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QC > 0 THEN 1 / VO.QC
 END) AS FATOR
    FROM TGFCAB C
    JOIN tops TP ON TP.CODTIPOPER = C.CODTIPOPER
    JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    JOIN TGFPRO P ON P.CODPROD = I.CODPROD
    LEFT JOIN voa VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
    CROSS JOIN prm PR
    WHERE TP.PAPEL = 'COTACAO'
      AND (NVL(I.PENDENTE, 'S') = 'S' AND NVL(I.CANCELADO, 'N') <> 'S' AND NVL(I.QTDNEG, 0) > NVL(I.QTDENTREGUE, 0))
      AND (PR.CODEMP = 0 OR C.CODEMP = PR.CODEMP)
),
cot AS (
    SELECT X.CODEMP, X.CODPROD,
           SUM(CASE WHEN X.FATOR IS NULL THEN 0 ELSE X.SALDO_ORIG * X.FATOR END) AS QTD_COTACAO,
           SUM(CASE WHEN X.FATOR IS NULL THEN 1 ELSE 0 END) AS N_COT_NAO_CONC
    FROM cot_it X
    GROUP BY X.CODEMP, X.CODPROD
),
-- Preço de REFERÊNCIA (não é custo): VLRTOT / quantidade na unidade padrão do item de OC confirmada
-- mais recente, dentro do horizonte, com unidade conciliada. Grupo PRINCIPAL e SEPARADO (ex.: TOP 1741)
-- nunca se misturam. Sem referência = NULL (nunca zero).
preco_it AS (
    SELECT I.CODPROD, TP.GRUPO_PRECO, C.NUNOTA, C.CODTIPOPER,
           TRUNC(C.DTNEG) AS DT_NEG,
           NVL(I.VLRTOT, 0) / (NVL(I.QTDNEG, 0) * (CASE WHEN I.CODVOL = P.CODVOL THEN 1
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QC > 0 THEN VO.QC
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QC > 0 THEN 1 / VO.QC
 END)) AS PRECO_BASE,
           ROW_NUMBER() OVER (PARTITION BY I.CODPROD, TP.GRUPO_PRECO
                              ORDER BY C.DTNEG DESC, C.NUNOTA DESC, I.SEQUENCIA DESC) AS RN
    FROM TGFCAB C
    JOIN tops TP ON TP.CODTIPOPER = C.CODTIPOPER
    JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    JOIN TGFPRO P ON P.CODPROD = I.CODPROD
    LEFT JOIN voa VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
    CROSS JOIN prm PR
    CROSS JOIN janc JC
    WHERE TP.PAPEL = 'ORDEM_COMPRA'
      AND C.STATUSNOTA = 'L'
      AND NVL(I.CANCELADO, 'N') <> 'S'
      AND NVL(I.QTDNEG, 0) > 0
      AND NVL(I.VLRTOT, 0) > 0
      AND (CASE WHEN I.CODVOL = P.CODVOL THEN 1
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QC > 0 THEN VO.QC
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QC > 0 THEN 1 / VO.QC
 END) IS NOT NULL
      AND C.DTNEG >= JC.HORIZ_INI
      AND C.DTNEG < JC.DT_BASE + 1
      AND (PR.CODEMP = 0 OR C.CODEMP = PR.CODEMP)
),
preco AS (
    SELECT X.CODPROD,
           MAX(CASE WHEN X.GRUPO_PRECO = 'PRINCIPAL' THEN X.PRECO_BASE END) AS PRECO_REF,
           MAX(CASE WHEN X.GRUPO_PRECO = 'PRINCIPAL' THEN X.DT_NEG END) AS PRECO_REF_DATA,
           MAX(CASE WHEN X.GRUPO_PRECO = 'PRINCIPAL' THEN X.NUNOTA END) AS PRECO_REF_NUNOTA,
           MAX(CASE WHEN X.GRUPO_PRECO = 'PRINCIPAL' THEN X.CODTIPOPER END) AS PRECO_REF_TOP,
           MAX(CASE WHEN X.GRUPO_PRECO = 'SEPARADO' THEN X.PRECO_BASE END) AS PRECO_SEP,
           MAX(CASE WHEN X.GRUPO_PRECO = 'SEPARADO' THEN X.DT_NEG END) AS PRECO_SEP_DATA
    FROM preco_it X
    WHERE X.RN = 1
    GROUP BY X.CODPROD
),
-- Universo: empresa+produto com estoque, consumo no horizonte, compromisso, OC aberta ou cotação.
chaves AS (
    SELECT ES.CODEMP, ES.CODPROD FROM est ES
     WHERE ES.QTD_ESTOQUE <> 0 OR ES.QTD_RESERVADO <> 0 OR ES.QTD_BLOQUEADO <> 0
    UNION SELECT MD.CODEMP, MD.CODPROD FROM med3 MD
    UNION SELECT CP.CODEMP, CP.CODPROD FROM cmp CP
    UNION SELECT OP.CODEMP, OP.CODPROD FROM oc_pos OP
    UNION SELECT CT.CODEMP, CT.CODPROD FROM cot CT
),
b1 AS (
    SELECT K.CODEMP, K.CODPROD,
           PD.DESCRPROD, PD.UNIDADE, PD.GRUPO, PD.GRUPO_DESCR, PD.ESTMIN_CAD, PD.AGRUPMIN, PD.LOTEMIN,
           PD.FL_CONSIGNADO, PD.COD_ANTIGO,
           JA.DT_BASE,
           NVL(ES.QTD_ESTOQUE, 0) AS QTD_ESTOQUE,
           NVL(ES.QTD_RESERVADO, 0) AS QTD_RESERVADO,
           NVL(ES.QTD_BLOQUEADO, 0) AS QTD_BLOQUEADO,
           NVL(CP.QTD_PEDIDOS, 0) AS QTD_PEDIDOS,
           NVL(CP.QTD_CONFERIDA, 0) AS QTD_CONFERIDA,
           NVL(CP.N_PED_NAO_CONC, 0) AS N_PED_NAO_CONC,
           NVL(MD.ORIGEM_SERIE, 'SEM_CONSUMO') AS ORIGEM_SERIE,
           MD.DT_PRIM_CONSUMO,
           NVL(MD.N_MESES, 0) AS N_MESES,
           NVL(MD.FRAC_USADA, 0) AS FRAC_USADA,
           NVL(MD.QTD_JANELA, 0) AS QTD_JANELA,
           NVL(MD.QTD_PARCIAL, 0) AS QTD_PARCIAL,
           MD.MEDIA_SIMPLES, MD.MEDIA_PONDERADA, MD.MEDIA_3M, MD.MEDIA_CALC,
           NVL(MD.FL_HIST_INSUF, 0) AS FL_HIST_INSUF,
           NVL(MD.N_CONS_NAO_CONC, 0) AS N_CONS_NAO_CONC,
           CASE WHEN MD.MEDIA_CALC < 0 THEN 1 ELSE 0 END AS FL_CONSUMO_NEG,
           NVL(OP.QTD_OC_CONF, 0) AS QTD_OC_CONF,
           NVL(OP.QTD_OC_CONF_PRAZO, 0) AS QTD_OC_CONF_PRAZO,
           NVL(OP.QTD_OC_CONF_ATRAS, 0) AS QTD_OC_CONF_ATRAS,
           NVL(OP.QTD_OC_CONF_SEMPREV, 0) AS QTD_OC_CONF_SEMPREV,
           NVL(OP.QTD_OC_NAO_CONF, 0) AS QTD_OC_NAO_CONF,
           NVL(OP.N_OCS_ABERTAS, 0) AS N_OCS_ABERTAS,
           NVL(OP.N_OC_NAO_CONC, 0) AS N_OC_NAO_CONC,
           NVL(OP.N_OC_SEM_PREV, 0) AS N_OC_SEM_PREV,
           NVL(OP.N_OC_ATRAS, 0) AS N_OC_ATRAS,
           NVL(OP.N_OC_ANTIGA, 0) AS N_OC_ANTIGA,
           NVL(OP.N_OC_TOP_SEP, 0) AS N_OC_TOP_SEP,
           CASE WHEN 0 = 1 THEN NVL(CT.QTD_COTACAO, 0) END AS QTD_COTACAO,
           NVL(CT.N_COT_NAO_CONC, 0) AS N_COT_NAO_CONC,
           PZ.PRECO_REF, PZ.PRECO_REF_DATA, PZ.PRECO_REF_NUNOTA, PZ.PRECO_REF_TOP, PZ.PRECO_SEP, PZ.PRECO_SEP_DATA,
           CASE WHEN PD.LT_CAD > 0 THEN PD.LT_CAD ELSE PR.LEADTIME_DEFAULT END AS LT,
           CASE WHEN PD.LT_CAD > 0 THEN 0 ELSE 1 END AS FL_LT_PADRAO,
           NVL(ES.QTD_ESTOQUE, 0)
             - CASE WHEN PR.DESCONTA_BLOQUEADO = 1 THEN NVL(ES.QTD_BLOQUEADO, 0) ELSE 0 END AS EFP,
           CASE WHEN PR.FONTE_COMPROMISSO = 2 THEN NVL(ES.QTD_RESERVADO, 0) ELSE NVL(CP.QTD_PEDIDOS, 0) END AS CMP,
           GREATEST(NVL(MD.MEDIA_CALC, 0), 0) AS MEDIA_USADA,
           GREATEST(NVL(MD.MEDIA_CALC, 0), 0) / PR.DIAS_MES AS DD,
           CASE WHEN GREATEST(NVL(MD.MEDIA_CALC, 0), 0) = 0 AND NVL(MD.ORIGEM_SERIE, 'SEM_CONSUMO') <> 'SO_MES_ATUAL'
                THEN 1 ELSE 0 END AS FL_SEM_GIRO
    FROM chaves K
    JOIN prod PD ON PD.CODPROD = K.CODPROD
    LEFT JOIN est ES ON ES.CODEMP = K.CODEMP AND ES.CODPROD = K.CODPROD
    LEFT JOIN cmp CP ON CP.CODEMP = K.CODEMP AND CP.CODPROD = K.CODPROD
    LEFT JOIN med3 MD ON MD.CODEMP = K.CODEMP AND MD.CODPROD = K.CODPROD
    LEFT JOIN oc_pos OP ON OP.CODEMP = K.CODEMP AND OP.CODPROD = K.CODPROD
    LEFT JOIN cot CT ON CT.CODEMP = K.CODEMP AND CT.CODPROD = K.CODPROD
    LEFT JOIN preco PZ ON PZ.CODPROD = K.CODPROD
    CROSS JOIN prm PR
    CROSS JOIN jan JA
),
-- Curva ABC OPCIONAL (ABC_CALCULADA = 1): valor = consumo líquido da série × preço de referência de compra.
-- Sem preço = sem curva. Ordenação: valor desc, código. Classe pela participação acumulada ANTES do item.
abc AS (
    SELECT B.CODEMP, B.CODPROD,
           CASE WHEN B.PRECO_REF IS NOT NULL AND B.QTD_JANELA > 0 THEN B.QTD_JANELA * B.PRECO_REF ELSE 0 END AS VALOR_ABC
    FROM b1 B
),
abc2 AS (
    SELECT A.CODEMP, A.CODPROD, A.VALOR_ABC,
           SUM(A.VALOR_ABC) OVER (PARTITION BY A.CODEMP) AS TOT_ABC,
           NVL(SUM(A.VALOR_ABC) OVER (PARTITION BY A.CODEMP ORDER BY A.VALOR_ABC DESC, A.CODPROD
                                      ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING), 0) AS ACUM_ANT
    FROM abc A
),
b2 AS (
    SELECT B.*,
           CASE WHEN PR.ABC_CALCULADA = 1 AND B.PRECO_REF IS NOT NULL AND A2.TOT_ABC > 0 THEN
                CASE WHEN A2.ACUM_ANT / A2.TOT_ABC < PR.ABC_LIMITE_A THEN 'A'
                     WHEN A2.ACUM_ANT / A2.TOT_ABC < PR.ABC_LIMITE_B THEN 'B'
                     ELSE 'C' END
           END AS CURVA,
           CASE WHEN PR.ABC_CALCULADA = 1 THEN 'CALCULADA' ELSE 'SEM_FONTE' END AS CURVA_ORIGEM,
           A2.VALOR_ABC
    FROM b1 B
    LEFT JOIN abc2 A2 ON A2.CODEMP = B.CODEMP AND A2.CODPROD = B.CODPROD
    CROSS JOIN prm PR
),
b3 AS (
    SELECT B.*,
           CASE B.CURVA WHEN 'A' THEN PR.COBERTURA_ALVO_A WHEN 'B' THEN PR.COBERTURA_ALVO_B
                        WHEN 'C' THEN PR.COBERTURA_ALVO_C ELSE PR.COBERTURA_SEM_CURVA END AS COB_ALVO,
           CASE PR.POLITICA_SEGURANCA WHEN 1 THEN B.DD * B.LT * PR.SEGURANCA_PCT_LT
                                      WHEN 2 THEN NVL(B.ESTMIN_CAD, 0)
                                      ELSE 0 END AS EST_SEG,
           B.EFP - B.CMP AS DISPONIVEL,
           B.EFP + B.QTD_OC_CONF AS POS_CONTRATADA
    FROM b2 B
    CROSS JOIN prm PR
),
b4 AS (
    SELECT B.*,
           B.LT + B.COB_ALVO AS HORIZONTE,
           (CASE WHEN PR.REGRA_PREVISAO_FIRME = 2 THEN B.CMP + B.DD * B.LT ELSE GREATEST(B.CMP, B.DD * B.LT) END) + B.EST_SEG AS PONTO_PEDIDO,
           (CASE WHEN PR.REGRA_PREVISAO_FIRME = 2 THEN B.CMP + B.DD * (B.LT + B.COB_ALVO) ELSE GREATEST(B.CMP, B.DD * (B.LT + B.COB_ALVO)) END) + B.EST_SEG AS REQUISITO,
           B.CMP + B.DD * (B.LT + B.COB_ALVO) + B.EST_SEG AS REQUISITO_SOMA,
           GREATEST(B.CMP, B.DD * (B.LT + B.COB_ALVO)) + B.EST_SEG AS REQUISITO_MAIOR,
           (CASE WHEN B.EFP < B.CMP THEN 0
      WHEN B.DD <= 0 THEN NULL
      ELSE (B.EFP - CASE WHEN PR.REGRA_PREVISAO_FIRME = 2 THEN B.CMP ELSE 0 END) / B.DD
 END) AS COB_FISICA_DIAS,
           (CASE WHEN (B.EFP + B.QTD_OC_CONF) < B.CMP THEN 0
      WHEN B.DD <= 0 THEN NULL
      ELSE ((B.EFP + B.QTD_OC_CONF) - CASE WHEN PR.REGRA_PREVISAO_FIRME = 2 THEN B.CMP ELSE 0 END) / B.DD
 END) AS COB_CONTRAT_DIAS
    FROM b3 B
    CROSS JOIN prm PR
),
-- Projeção agregada (consumo médio constante) com recebimentos de data confiável, em ordem.
-- Falta antes do recebimento i: a oferta acumulada até ali não cobre a demanda até a data dele.
proj AS (
    SELECT B.CODEMP, B.CODPROD, R.DT_PREV,
           R.DT_PREV - B.DT_BASE AS D_I,
           (CASE WHEN (B.EFP + R.ACUM_ANTES) < B.CMP THEN 0
      WHEN B.DD <= 0 THEN NULL
      ELSE ((B.EFP + R.ACUM_ANTES) - CASE WHEN PR.REGRA_PREVISAO_FIRME = 2 THEN B.CMP ELSE 0 END) / B.DD
 END) AS T_ANTES,
           (CASE WHEN PR.REGRA_PREVISAO_FIRME = 2 THEN B.CMP + B.DD * (R.DT_PREV - B.DT_BASE) ELSE GREATEST(B.CMP, B.DD * (R.DT_PREV - B.DT_BASE)) END) - (B.EFP + R.ACUM_ANTES) AS FALTA_ANTES
    FROM b4 B
    JOIN rec2 R ON R.CODEMP = B.CODEMP AND R.CODPROD = B.CODPROD
    CROSS JOIN prm PR
),
proj1 AS (
    SELECT P.CODEMP, P.CODPROD, P.DT_PREV, P.T_ANTES, P.FALTA_ANTES,
           ROW_NUMBER() OVER (PARTITION BY P.CODEMP, P.CODPROD ORDER BY P.DT_PREV) AS RN
    FROM proj P
    WHERE P.T_ANTES IS NOT NULL AND P.T_ANTES < P.D_I
),
recsum AS (
    SELECT R.CODEMP, R.CODPROD, SUM(R.QTD) AS QTD_DATADA, MIN(R.DT_PREV) AS DT_PROX_RECEB,
           SUM(CASE WHEN R.ORDEM_REC = 1 THEN R.QTD ELSE 0 END) AS QTD_PROX_RECEB
    FROM rec2 R
    GROUP BY R.CODEMP, R.CODPROD
),
b5 AS (
    SELECT B.*,
           RS.DT_PROX_RECEB,
           RS.QTD_PROX_RECEB,
           NVL(RS.QTD_DATADA, 0) AS QTD_OC_DATADA,
           CASE WHEN P1.CODPROD IS NOT NULL THEN 1 ELSE 0 END AS FL_FALTA_ANTES_RECEB,
           P1.DT_PREV AS DT_RECEB_APOS_FALTA,
           P1.FALTA_ANTES AS QTD_FALTA_ANTES_RECEB,
           CASE WHEN P1.CODPROD IS NOT NULL THEN P1.T_ANTES
                ELSE (CASE WHEN (B.EFP + NVL(RS.QTD_DATADA, 0)) < B.CMP THEN 0
      WHEN B.DD <= 0 THEN NULL
      ELSE ((B.EFP + NVL(RS.QTD_DATADA, 0)) - CASE WHEN PR.REGRA_PREVISAO_FIRME = 2 THEN B.CMP ELSE 0 END) / B.DD
 END)
           END AS T_FALTA_PROJ
    FROM b4 B
    LEFT JOIN proj1 P1 ON P1.CODEMP = B.CODEMP AND P1.CODPROD = B.CODPROD AND P1.RN = 1
    LEFT JOIN recsum RS ON RS.CODEMP = B.CODEMP AND RS.CODPROD = B.CODPROD
    CROSS JOIN prm PR
),
b6 AS (
    SELECT B.*,
           -- Data só quando cabe em 10 anos (evita estouro de DATE com demanda ínfima).
           CASE WHEN B.T_FALTA_PROJ IS NOT NULL AND B.T_FALTA_PROJ <= 3650
                THEN B.DT_BASE + CAST(FLOOR(B.T_FALTA_PROJ) AS INTEGER) END AS DT_FALTA_EST,
           CASE WHEN B.FL_CONSIGNADO = 1 THEN 0 ELSE GREATEST(B.REQUISITO - B.POS_CONTRATADA, 0) END AS NEC_BRUTA,
           CASE WHEN B.FL_CONSIGNADO = 1 THEN 0 ELSE GREATEST(B.REQUISITO_SOMA - B.POS_CONTRATADA, 0) END AS NEC_SOMA,
           CASE WHEN B.FL_CONSIGNADO = 1 THEN 0 ELSE GREATEST(B.REQUISITO_MAIOR - B.POS_CONTRATADA, 0) END AS NEC_MAIOR
    FROM b5 B
),
-- Decomposição: OC não confirmada e cotação abatem o que ainda falta SOLICITAR, mas não viram cobertura contratada.
b7 AS (
    SELECT B.*,
           LEAST(B.QTD_OC_NAO_CONF, B.NEC_BRUTA) AS NEC_EM_OC_NAO_CONF
    FROM b6 B
),
b8 AS (
    SELECT B.*,
           CASE WHEN 0 = 1
                THEN LEAST(NVL(B.QTD_COTACAO, 0), B.NEC_BRUTA - B.NEC_EM_OC_NAO_CONF) END AS NEC_EM_COTACAO
    FROM b7 B
),
b9 AS (
    SELECT B.*,
           B.NEC_BRUTA - B.NEC_EM_OC_NAO_CONF - NVL(B.NEC_EM_COTACAO, 0) AS NEC_NAO_SOLIC,
           CASE WHEN NVL(B.LOTEMIN, 0) < 0 OR NVL(B.AGRUPMIN, 0) < 0 THEN 1 ELSE 0 END AS FL_LOTE_INVALIDO
    FROM b8 B
),
-- Lote mínimo primeiro, depois múltiplo: o resultado atende os dois. Só com LOTE_MULTIPLO = 1.
b10 AS (
    SELECT B.*,
           CASE WHEN PR.LOTE_MULTIPLO = 1 AND B.NEC_NAO_SOLIC > 0 THEN
                CASE WHEN NVL(B.AGRUPMIN, 0) > 0
                     THEN CEIL(ROUND(GREATEST(B.NEC_NAO_SOLIC, CASE WHEN B.LOTEMIN > 0 THEN B.LOTEMIN ELSE 0 END)
                                     / B.AGRUPMIN, 6)) * B.AGRUPMIN
                     ELSE GREATEST(B.NEC_NAO_SOLIC, CASE WHEN B.LOTEMIN > 0 THEN B.LOTEMIN ELSE 0 END)
                END
           END AS QTD_ARRED
    FROM b9 B
    CROSS JOIN prm PR
),
plano AS (
    SELECT B.*,
           CASE WHEN B.QTD_ARRED IS NOT NULL THEN B.QTD_ARRED - B.NEC_NAO_SOLIC END AS EXCESSO_ARRED,
           CASE WHEN B.PRECO_REF IS NOT NULL AND B.DISPONIVEL < 0 THEN -B.DISPONIVEL * B.PRECO_REF END AS VLR_FALTA_ATUAL,
           CASE WHEN B.PRECO_REF IS NOT NULL THEN B.NEC_NAO_SOLIC * B.PRECO_REF END AS VLR_NEC_NAO_SOLIC,
           B.N_CONS_NAO_CONC + B.N_PED_NAO_CONC + B.N_OC_NAO_CONC + B.N_COT_NAO_CONC AS N_NAO_CONC,
           CASE WHEN B.QTD_ESTOQUE < 0 OR B.COB_FISICA_DIAS = 0 THEN 'P1_CRITICO'
                WHEN B.T_FALTA_PROJ IS NOT NULL AND FLOOR(B.T_FALTA_PROJ) < B.LT THEN 'P2_RUPTURA_IMINENTE'
                WHEN B.POS_CONTRATADA < B.PONTO_PEDIDO + B.DD * PR.MARGEM_ATENCAO_DIAS THEN 'P3_ATENCAO'
                WHEN B.FL_SEM_GIRO = 1 AND B.QTD_ESTOQUE > 0 AND (B.QTD_PEDIDOS > 0 OR B.CMP > 0) THEN 'REVISAR_SEM_GIRO'
                WHEN B.DD > 0 AND B.COB_CONTRAT_DIAS > PR.COBERTURA_MAX_DIAS THEN 'P0_EXCESSO'
                WHEN B.FL_SEM_GIRO = 1 AND B.QTD_ESTOQUE > 0 THEN 'P0_SEM_GIRO'
                ELSE 'OK' END AS PRIORIDADE,
           CASE WHEN B.QTD_ESTOQUE < 0 THEN 'ESTOQUE_NEGATIVO;' ELSE '' END
           || CASE WHEN B.DISPONIVEL < 0 THEN 'COMPROMISSO_MAIOR_QUE_ESTOQUE;' ELSE '' END
           || CASE WHEN B.COB_FISICA_DIAS = 0 AND B.QTD_ESTOQUE >= 0 AND B.DISPONIVEL >= 0 THEN 'SEM_COBERTURA_FISICA;' ELSE '' END
           || CASE WHEN B.FL_FALTA_ANTES_RECEB = 1 THEN 'FALTA_ANTES_RECEBIMENTO;' ELSE '' END
           || CASE WHEN B.T_FALTA_PROJ IS NOT NULL AND FLOOR(B.T_FALTA_PROJ) < B.LT THEN 'FALTA_DENTRO_LEAD_TIME;' ELSE '' END
           || CASE WHEN B.POS_CONTRATADA < B.PONTO_PEDIDO THEN 'ABAIXO_PONTO_PEDIDO;'
                   WHEN B.POS_CONTRATADA < B.PONTO_PEDIDO + B.DD * PR.MARGEM_ATENCAO_DIAS THEN 'PROXIMO_PONTO_PEDIDO;'
                   ELSE '' END
           || CASE WHEN B.FL_SEM_GIRO = 1 AND B.QTD_ESTOQUE > 0 AND (B.QTD_PEDIDOS > 0 OR B.CMP > 0) THEN 'SEM_GIRO_COM_COMPROMISSO;'
                   WHEN B.FL_SEM_GIRO = 1 AND B.QTD_ESTOQUE > 0 THEN 'SEM_GIRO;'
                   ELSE '' END
           || CASE WHEN B.DD > 0 AND B.COB_CONTRAT_DIAS > PR.COBERTURA_MAX_DIAS THEN 'COBERTURA_ACIMA_MAXIMO;' ELSE '' END
           || CASE WHEN B.FL_HIST_INSUF = 1 THEN 'HISTORICO_INSUFICIENTE;' ELSE '' END
           || CASE WHEN B.FL_CONSUMO_NEG = 1 THEN 'CONSUMO_LIQUIDO_NEGATIVO;' ELSE '' END
           || CASE WHEN B.N_CONS_NAO_CONC + B.N_PED_NAO_CONC + B.N_OC_NAO_CONC + B.N_COT_NAO_CONC > 0
                   THEN 'UNIDADE_NAO_CONCILIADA;' ELSE '' END
           || CASE WHEN B.QTD_OC_NAO_CONF > 0 THEN 'OC_NAO_CONFIRMADA;' ELSE '' END
           || CASE WHEN B.N_OC_ATRAS > 0 THEN 'OC_ATRASADA;' ELSE '' END
           || CASE WHEN B.N_OC_SEM_PREV > 0 THEN 'OC_SEM_PREVISAO;' ELSE '' END
           || CASE WHEN B.N_OC_ANTIGA > 0 THEN 'OC_ANTIGA_ABERTA;' ELSE '' END
           || CASE WHEN B.PRECO_REF IS NULL THEN 'SEM_PRECO_REFERENCIA;' ELSE '' END
           || CASE WHEN B.FL_LT_PADRAO = 1 THEN 'LEAD_TIME_PADRAO;' ELSE '' END
           || CASE WHEN B.FL_CONSIGNADO = 1 THEN 'CONSIGNADO_SEM_CALCULO;' ELSE '' END
           || CASE WHEN B.ESTMIN_CAD > 0 AND B.DISPONIVEL < B.ESTMIN_CAD THEN 'ABAIXO_ESTMIN_CADASTRO;' ELSE '' END
           || CASE WHEN B.FL_LOTE_INVALIDO = 1 THEN 'LOTE_MULTIPLO_INVALIDO;' ELSE '' END AS MOTIVOS
    FROM b10 B
    CROSS JOIN prm PR
),
res AS (
    SELECT PL.PRIORIDADE,
           COUNT(*) AS N_SKUS,
           SUM(CASE WHEN PL.DISPONIVEL < 0 THEN 1 ELSE 0 END) AS N_FALTA_ATUAL,
           SUM(NVL(PL.VLR_FALTA_ATUAL, 0)) AS VLR_FALTA_ATUAL,
           SUM(CASE WHEN PL.DISPONIVEL < 0 AND PL.PRECO_REF IS NULL THEN 1 ELSE 0 END) AS N_FALTA_SEM_PRECO,
           SUM(CASE WHEN PL.NEC_NAO_SOLIC > 0 THEN 1 ELSE 0 END) AS N_NEC,
           SUM(NVL(PL.VLR_NEC_NAO_SOLIC, 0)) AS VLR_NEC_NAO_SOLIC,
           SUM(CASE WHEN PL.NEC_NAO_SOLIC > 0 AND PL.PRECO_REF IS NULL THEN 1 ELSE 0 END) AS N_NEC_SEM_PRECO,
           SUM(CASE WHEN PL.NEC_EM_OC_NAO_CONF > 0 THEN 1 ELSE 0 END) AS N_NEC_OC_NAO_CONF,
           SUM(CASE WHEN PL.NEC_EM_COTACAO > 0 THEN 1 ELSE 0 END) AS N_NEC_COTACAO,
           SUM(PL.FL_FALTA_ANTES_RECEB) AS N_FALTA_ANTES_RECEB,
           SUM(PL.FL_HIST_INSUF) AS N_HIST_INSUF,
           SUM(CASE WHEN PL.N_NAO_CONC > 0 THEN 1 ELSE 0 END) AS N_UN_NAO_CONC,
           SUM(CASE WHEN PL.PRECO_REF IS NULL THEN 1 ELSE 0 END) AS N_SEM_PRECO,
           SUM(PL.FL_LT_PADRAO) AS N_LT_PADRAO,
           SUM(CASE WHEN PL.N_OC_ATRAS > 0 THEN 1 ELSE 0 END) AS N_OC_ATRAS,
           SUM(CASE WHEN PL.N_OC_SEM_PREV > 0 THEN 1 ELSE 0 END) AS N_OC_SEM_PREV,
           SUM(CASE WHEN PL.QTD_OC_NAO_CONF > 0 THEN 1 ELSE 0 END) AS N_OC_NAO_CONF,
           SUM(CASE WHEN PL.N_OC_ANTIGA > 0 THEN 1 ELSE 0 END) AS N_OC_ANTIGA,
           SUM(CASE WHEN PL.N_OC_TOP_SEP > 0 THEN 1 ELSE 0 END) AS N_OC_TOP_SEP,
           SUM(PL.FL_CONSIGNADO) AS N_CONSIGNADO,
           SUM(PL.FL_LOTE_INVALIDO) AS N_LOTE_INVALIDO,
           SUM(PL.FL_CONSUMO_NEG) AS N_CONSUMO_NEG,
           SUM(CASE WHEN PL.CURVA IS NULL THEN 1 ELSE 0 END) AS N_SEM_CURVA
    FROM plano PL
    GROUP BY PL.PRIORIDADE
)
SELECT R.PRIORIDADE, R.N_SKUS, R.N_FALTA_ATUAL,
       ROUND(R.VLR_FALTA_ATUAL, 2) AS VLR_FALTA_ATUAL,
       R.N_FALTA_SEM_PRECO, R.N_NEC,
       ROUND(R.VLR_NEC_NAO_SOLIC, 2) AS VLR_NEC_NAO_SOLIC,
       R.N_NEC_SEM_PRECO, R.N_NEC_OC_NAO_CONF, R.N_NEC_COTACAO, R.N_FALTA_ANTES_RECEB, R.N_HIST_INSUF,
       R.N_UN_NAO_CONC, R.N_SEM_PRECO, R.N_LT_PADRAO, R.N_OC_ATRAS, R.N_OC_SEM_PREV, R.N_OC_NAO_CONF,
       R.N_OC_ANTIGA, R.N_OC_TOP_SEP, R.N_CONSIGNADO, R.N_LOTE_INVALIDO, R.N_CONSUMO_NEG, R.N_SEM_CURVA,
       0 AS COTACAO_MAPEADA,
       TO_CHAR(JC.DT_BASE, 'YYYY-MM-DD') AS DT_BASE,
       JA.SNAPSHOT,
       TO_CHAR(JC.INI, 'YYYY-MM-DD') AS JANELA_INI,
       TO_CHAR(ADD_MONTHS(JC.M0, -1), 'YYYY-MM-DD') AS JANELA_FIM,
       ROUND(JC.FRAC, 4) AS FRAC_PARCIAL,
       (SELECT COUNT(*) FROM TGFPRO PX WHERE PX.ATIVO = 'S'
           AND PX.CODPROD NOT IN (SELECT KX.CODPROD FROM chaves KX)) AS N_ATIVOS_FORA
FROM res R
CROSS JOIN janc JC
CROSS JOIN jan JA
ORDER BY (CASE R.PRIORIDADE WHEN 'P1_CRITICO' THEN 1 WHEN 'P2_RUPTURA_IMINENTE' THEN 2 WHEN 'P3_ATENCAO' THEN 3
         WHEN 'REVISAR_SEM_GIRO' THEN 4 WHEN 'P0_EXCESSO' THEN 5 WHEN 'P0_SEM_GIRO' THEN 6 ELSE 7 END)
