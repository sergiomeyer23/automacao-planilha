-- Consulta: Q_CARTEIRA
-- Indicadores agregados da carteira de OC em blocos (uma linha por bloco+chave). N_AUX: ABERTO = itens com unidade não conciliada; PONTUALIDADE/VINCULO/QUALIDADE = 0.
-- Binds na ordem dos '?': CODEMP:I, DT_INI:S, DT_FIM:S, TOLERANCIA_ATRASO_DIAS:I, OC_ANTIGA_MESES:I

WITH prm AS (
    SELECT CAST(TO_NUMBER(?) AS INTEGER) AS CODEMP,
           TO_DATE(?, 'YYYY-MM-DD') AS DT_INI,
           TO_DATE(?, 'YYYY-MM-DD') AS DT_FIM,
           CAST(TO_NUMBER(?) AS INTEGER) AS TOLERANCIA_ATRASO_DIAS,
           CAST(TO_NUMBER(?) AS INTEGER) AS OC_ANTIGA_MESES
    FROM DUAL
),
-- Papéis das TOPs gerados de config/painel.json (não validados)
tops AS (
    SELECT 1131 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1118 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1117 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1729 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1130 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1727 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1724 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1730 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1781 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1782 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1738 AS CODTIPOPER, 'CONSUMO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1200 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1201 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1211 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1206 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1000 AS CODTIPOPER, 'EMPENHO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1005 AS CODTIPOPER, 'EMPENHO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1008 AS CODTIPOPER, 'EMPENHO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1002 AS CODTIPOPER, 'EMPENHO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1009 AS CODTIPOPER, 'EMPENHO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1001 AS CODTIPOPER, 'EMPENHO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1728 AS CODTIPOPER, 'EMPENHO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1010 AS CODTIPOPER, 'EMPENHO' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 99 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL, 'PRINCIPAL' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 100 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL, 'PRINCIPAL' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 101 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL, 'PRINCIPAL' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 108 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL, 'PRINCIPAL' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1741 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL, 'SEPARADO' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 1742 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL, 'PRINCIPAL' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 259 AS CODTIPOPER, 'ENTRADA_POR_OS' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
    UNION ALL SELECT 200 AS CODTIPOPER, 'ENTRADA_POR_OS' AS PAPEL, 'NA' AS GRUPO_PRECO FROM DUAL
),
-- Data-base do cálculo: data do BANCO (SYSDATE), nunca do navegador.
-- A posição de estoque (TGFEST) é sempre a atual; por isso a data-base é hoje.
jan AS (
    SELECT TRUNC(SYSDATE) AS DT_BASE,
           TRUNC(SYSDATE, 'MM') AS M0,
           TO_CHAR(SYSDATE, 'DD/MM/YYYY HH24:MI') AS SNAPSHOT
    FROM DUAL
),
-- Regras de conversão ativas, agrupadas ANTES do join (nunca multiplicam linhas).
-- Mais de uma regra distinta para o mesmo produto+unidade = AMBIGUA (não converte).
voa AS (
    SELECT V.CODPROD, V.CODVOL,
           MAX(V.DIVIDEMULTIPLICA) AS DM,
           MAX(V.QUANTIDADE) AS QC,
           COUNT(DISTINCT NVL(V.DIVIDEMULTIPLICA, '-') || '|' || NVL(CAST(V.QUANTIDADE AS VARCHAR(40)), '-')) AS N_REGRAS
    FROM TGFVOA V
    WHERE NVL(V.ATIVO, 'S') = 'S'
    GROUP BY V.CODPROD, V.CODVOL
),
-- Itens de OC do escopo da carteira: negociados no período (qualquer status) OU com saldo aberto (qualquer data).
occ_it AS (
    SELECT C.NUNOTA, I.SEQUENCIA, C.CODEMP, C.CODTIPOPER, C.DHTIPOPER, C.CODPARC, TP.GRUPO_PRECO, I.CODPROD,
           C.STATUSNOTA,
           TRUNC(C.DTNEG) AS DT_NEG,
           TRUNC(C.DTPREVENT) AS DT_PREV,
           NVL(I.PENDENTE, 'S') AS PENDENTE,
           NVL(I.CANCELADO, 'N') AS CANCELADO,
           NVL(I.QTDNEG, 0) AS QTDNEG,
           NVL(I.QTDENTREGUE, 0) AS QTDENT,
           NVL(I.VLRTOT, 0) AS VLRTOT,
           I.CODVOL AS UNID_ITEM,
           P.CODVOL AS UNID_PADRAO,
           CASE WHEN P.LEADTIME > 0 THEN P.LEADTIME END AS LT_CAD,
           NULLIF(TRIM(C.AD_OSTUICIAL), '') AS OS,
           (CASE WHEN I.CODVOL = P.CODVOL THEN 1
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QC > 0 THEN VO.QC
      WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QC > 0 THEN 1 / VO.QC
 END) AS FATOR,
           (CASE WHEN I.CODVOL IS NULL THEN 'SEM_UNIDADE'
      WHEN I.CODVOL = P.CODVOL THEN 'PADRAO'
      WHEN VO.CODPROD IS NULL THEN 'SEM_REGRA'
      WHEN VO.N_REGRAS > 1 THEN 'AMBIGUA'
      WHEN VO.DM = 'M' AND VO.QC > 0 THEN 'MULTIPLICA'
      WHEN VO.DM = 'D' AND VO.QC > 0 THEN 'DIVIDE'
      ELSE 'REGRA_INVALIDA'
 END) AS STATUS_CONV,
           CASE WHEN C.DTNEG >= PR.DT_INI AND C.DTNEG < PR.DT_FIM + 1 THEN 1 ELSE 0 END AS FL_PERIODO,
           CASE WHEN (NVL(I.PENDENTE, 'S') = 'S' AND NVL(I.CANCELADO, 'N') <> 'S' AND NVL(I.QTDNEG, 0) > NVL(I.QTDENTREGUE, 0)) THEN 1 ELSE 0 END AS FL_ABERTO
    FROM TGFCAB C
    JOIN tops TP ON TP.CODTIPOPER = C.CODTIPOPER
    JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    JOIN TGFPRO P ON P.CODPROD = I.CODPROD
    LEFT JOIN voa VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
    CROSS JOIN prm PR
    WHERE TP.PAPEL = 'ORDEM_COMPRA'
      AND (PR.CODEMP = 0 OR C.CODEMP = PR.CODEMP)
      AND ((C.DTNEG >= PR.DT_INI AND C.DTNEG < PR.DT_FIM + 1) OR (NVL(I.PENDENTE, 'S') = 'S' AND NVL(I.CANCELADO, 'N') <> 'S' AND NVL(I.QTDNEG, 0) > NVL(I.QTDENTREGUE, 0)))
),
occ_lib AS (
    SELECT L.NUCHAVE,
           SUM(CASE WHEN L.DHLIB IS NULL AND NVL(L.REPROVADO, 'N') <> 'S' THEN 1 ELSE 0 END) AS N_LIB_PEND,
           SUM(CASE WHEN NVL(L.REPROVADO, 'N') = 'S' THEN 1 ELSE 0 END) AS N_LIB_REPROV
    FROM TSILIB L
    WHERE L.TABELA = 'TGFCAB'
      AND L.NUCHAVE IN (SELECT OI.NUNOTA FROM occ_it OI)
    GROUP BY L.NUCHAVE
),
-- Vínculo NATIVO: documentos derivados confirmados (TGFVAR). Só a DATA é usada; a quantidade
-- atendida vem de TGFITE.QTDENTREGUE (registro do sistema, pode refletir customização).
occ_var AS (
    SELECT V.NUNOTAORIG, V.SEQUENCIAORIG,
           COUNT(DISTINCT V.NUNOTA) AS N_DERIV,
           MAX(TRUNC(N.DTNEG)) AS DT_ULT_DERIV
    FROM TGFVAR V
    JOIN TGFCAB N ON N.NUNOTA = V.NUNOTA
    WHERE N.STATUSNOTA = 'L'
      AND V.NUNOTA <> V.NUNOTAORIG
      AND V.NUNOTAORIG IN (SELECT OI.NUNOTA FROM occ_it OI)
    GROUP BY V.NUNOTAORIG, V.SEQUENCIAORIG
),
-- Vínculo INFERIDO por OS + produto (TOPs ENTRADA_POR_OS). Não comprova vínculo: a mesma entrada
-- pode casar com várias OCs; isso é contado e exibido, nunca somado como recebimento.
occ_os_par AS (
    SELECT O.NUNOTA, O.SEQUENCIA, E.NUNOTA AS NUNOTA_ENT, E.SEQUENCIA AS SEQ_ENT, TRUNC(N.DTNEG) AS DT_ENT
    FROM occ_it O
    JOIN TGFITE E ON E.CODPROD = O.CODPROD AND NULLIF(TRIM(E.AD_OS), '') = O.OS
    JOIN TGFCAB N ON N.NUNOTA = E.NUNOTA
    JOIN tops TE ON TE.CODTIPOPER = N.CODTIPOPER
    WHERE TE.PAPEL = 'ENTRADA_POR_OS'
      AND O.OS IS NOT NULL
      AND N.STATUSNOTA = 'L'
      AND N.DTNEG >= O.DT_NEG
),
occ_os AS (
    SELECT X.NUNOTA, X.SEQUENCIA,
           COUNT(*) AS N_ENT_OS,
           MAX(X.DT_ENT) AS DT_ULT_ENT_OS,
           MAX(X.N_OC_MESMA_ENT) AS MAX_OC_MESMA_ENT
    FROM (SELECT Y.NUNOTA, Y.SEQUENCIA, Y.DT_ENT,
                 COUNT(*) OVER (PARTITION BY Y.NUNOTA_ENT, Y.SEQ_ENT) AS N_OC_MESMA_ENT
          FROM occ_os_par Y) X
    GROUP BY X.NUNOTA, X.SEQUENCIA
),
occ AS (
    SELECT O.NUNOTA, O.SEQUENCIA, O.CODEMP, O.CODTIPOPER, O.DHTIPOPER, O.CODPARC, O.GRUPO_PRECO, O.CODPROD,
           O.STATUSNOTA, O.DT_NEG, O.DT_PREV, O.PENDENTE, O.CANCELADO, O.QTDNEG, O.QTDENT, O.VLRTOT,
           O.UNID_ITEM, O.UNID_PADRAO, O.OS, O.FATOR, O.STATUS_CONV, O.FL_PERIODO, O.FL_ABERTO,
           CASE WHEN O.LT_CAD IS NOT NULL THEN TRUNC(O.DT_NEG + O.LT_CAD) END AS DT_PREV_ESTIMADA,
           NVL(LB.N_LIB_PEND, 0) AS N_LIB_PEND,
           NVL(LB.N_LIB_REPROV, 0) AS N_LIB_REPROV,
           (CASE WHEN O.STATUSNOTA = 'L' AND NVL(LB.N_LIB_PEND, 0) = 0 AND NVL(LB.N_LIB_REPROV, 0) = 0 THEN 'CONFIRMADA'
      WHEN O.STATUSNOTA = 'L' THEN 'APROVACAO_NAO_DETERMINADA'
      ELSE 'NAO_CONFIRMADA'
 END) AS SITUACAO,
           (CASE WHEN O.DT_PREV IS NULL THEN 'SEM_PREVISAO'
      WHEN O.DT_PREV < JA.DT_BASE THEN 'ATRASADA'
      ELSE 'NO_PRAZO'
 END) AS PRAZO,
           (CASE WHEN O.CANCELADO = 'S' THEN 'CANCELADA'
      WHEN O.QTDNEG > 0 AND O.QTDENT >= O.QTDNEG THEN 'ATENDIDA_INTEGRAL'
      WHEN O.PENDENTE = 'N' AND O.QTDENT > 0 THEN 'ENCERRADA_COM_SALDO'
      WHEN O.PENDENTE = 'N' THEN 'ENCERRADA_SEM_ATENDIMENTO'
      WHEN O.QTDENT > 0 THEN 'ATENDIMENTO_PARCIAL'
      ELSE 'ABERTA_SEM_ATENDIMENTO'
 END) AS STATUS_ITEM,
           CASE WHEN O.FL_ABERTO = 1 AND O.DT_PREV < JA.DT_BASE THEN JA.DT_BASE - O.DT_PREV END AS DIAS_ATRASO,
           JA.DT_BASE - O.DT_NEG AS IDADE_DIAS,
           CASE WHEN O.DT_NEG < ADD_MONTHS(JA.DT_BASE, -PR.OC_ANTIGA_MESES) THEN 1 ELSE 0 END AS FL_ANTIGA,
           CASE WHEN O.FL_ABERTO = 1 AND O.QTDNEG > 0
                THEN O.VLRTOT * (O.QTDNEG - O.QTDENT) / O.QTDNEG ELSE 0 END AS VLR_SALDO,
           CASE WHEN O.FL_ABERTO = 1 AND O.FATOR IS NOT NULL
                THEN (O.QTDNEG - O.QTDENT) * O.FATOR END AS SALDO_BASE,
           CASE WHEN O.PENDENTE = 'N' AND O.CANCELADO <> 'S' AND O.QTDENT > 0 AND O.QTDENT < O.QTDNEG
                THEN O.QTDNEG - O.QTDENT ELSE 0 END AS SALDO_ENCERRADO_ORIG,
           CASE WHEN O.QTDENT > O.QTDNEG THEN 1 ELSE 0 END AS FL_ACIMA_NEGOCIADO,
           NVL(VA.N_DERIV, 0) AS N_DERIV,
           VA.DT_ULT_DERIV,
           NVL(OSX.N_ENT_OS, 0) AS N_ENT_OS,
           OSX.DT_ULT_ENT_OS,
           NVL(OSX.MAX_OC_MESMA_ENT, 0) AS MAX_OC_MESMA_ENT,
           CASE WHEN NVL(VA.N_DERIV, 0) > 0 THEN 'NATIVO_TGFVAR'
                WHEN NVL(OSX.N_ENT_OS, 0) > 0 AND NVL(OSX.MAX_OC_MESMA_ENT, 0) > 1 THEN 'INFERIDO_OS_COMPARTILHADO'
                WHEN NVL(OSX.N_ENT_OS, 0) > 0 THEN 'INFERIDO_OS'
                WHEN O.QTDENT > 0 THEN 'ATENDIMENTO_SEM_VINCULO'
                ELSE 'SEM_ATENDIMENTO' END AS QUALIDADE_VINC
    FROM occ_it O
    LEFT JOIN occ_lib LB ON LB.NUCHAVE = O.NUNOTA
    LEFT JOIN occ_var VA ON VA.NUNOTAORIG = O.NUNOTA AND VA.SEQUENCIAORIG = O.SEQUENCIA
    LEFT JOIN occ_os OSX ON OSX.NUNOTA = O.NUNOTA AND OSX.SEQUENCIA = O.SEQUENCIA
    CROSS JOIN jan JA
    CROSS JOIN prm PR
),
occ_fx AS (
    SELECT O.NUNOTA, O.VLR_SALDO,
           CASE WHEN O.IDADE_DIAS <= 15 THEN '1_0_15'
                WHEN O.IDADE_DIAS <= 30 THEN '2_16_30'
                WHEN O.IDADE_DIAS <= 60 THEN '3_31_60'
                WHEN O.IDADE_DIAS <= 180 THEN '4_61_180'
                ELSE '5_181_MAIS' END AS FAIXA
    FROM occ O
    WHERE O.FL_ABERTO = 1
),
-- Indicador APROXIMADO (não é OTIF): itens confirmados com previsão no período e já vencida.
occ_pont AS (
    SELECT O.NUNOTA, O.VLRTOT,
           CASE WHEN O.STATUS_ITEM = 'ATENDIDA_INTEGRAL' AND O.N_DERIV > 0
                     AND O.DT_ULT_DERIV <= O.DT_PREV + PR.TOLERANCIA_ATRASO_DIAS THEN 'INTEGRAL_NO_PRAZO'
                WHEN O.STATUS_ITEM = 'ATENDIDA_INTEGRAL' AND O.N_DERIV > 0 THEN 'INTEGRAL_FORA_PRAZO'
                WHEN O.STATUS_ITEM = 'ATENDIDA_INTEGRAL' THEN 'EXCLUIDO_SEM_DATA_CONFIAVEL'
                WHEN O.STATUS_ITEM IN ('ENCERRADA_COM_SALDO', 'ENCERRADA_SEM_ATENDIMENTO') THEN 'ENCERRADA_SEM_INTEGRAL'
                ELSE 'NAO_ATENDIDA_VENCIDA' END AS CLASSE
    FROM occ O
    CROSS JOIN prm PR
    CROSS JOIN jan JA
    WHERE O.SITUACAO = 'CONFIRMADA'
      AND O.CANCELADO <> 'S'
      AND O.QTDNEG > 0
      AND O.DT_PREV >= PR.DT_INI AND O.DT_PREV < PR.DT_FIM + 1
      AND O.DT_PREV < JA.DT_BASE
),
occ_q AS (
    SELECT 'OC_SEM_PREVISAO' AS CHAVE, O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.PRAZO = 'SEM_PREVISAO'
    UNION ALL SELECT 'UNIDADE_NAO_CONCILIADA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.FATOR IS NULL
    UNION ALL SELECT 'OC_ANTIGA_ABERTA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.FL_ANTIGA = 1
    UNION ALL SELECT 'NAO_CONFIRMADA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.SITUACAO = 'NAO_CONFIRMADA'
    UNION ALL SELECT 'APROVACAO_NAO_DETERMINADA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.SITUACAO = 'APROVACAO_NAO_DETERMINADA'
    UNION ALL SELECT 'ACIMA_NEGOCIADO', O.NUNOTA FROM occ O WHERE O.FL_ACIMA_NEGOCIADO = 1
    UNION ALL SELECT 'ENCERRADA_COM_SALDO', O.NUNOTA FROM occ O WHERE O.FL_PERIODO = 1 AND O.STATUS_ITEM = 'ENCERRADA_COM_SALDO'
    UNION ALL SELECT 'ENTRADA_OS_COMPARTILHADA', O.NUNOTA FROM occ O WHERE O.MAX_OC_MESMA_ENT > 1
    UNION ALL SELECT 'TOP_PRECO_SEPARADO_ABERTA', O.NUNOTA FROM occ O WHERE O.FL_ABERTO = 1 AND O.GRUPO_PRECO = 'SEPARADO'
),
blocos AS (
    SELECT 'ABERTO' AS BLOCO, O.SITUACAO AS CHAVE, O.PRAZO AS CHAVE2,
           COUNT(DISTINCT O.NUNOTA) AS N_OCS, COUNT(*) AS N_ITENS, SUM(O.VLR_SALDO) AS VLR,
           SUM(CASE WHEN O.FATOR IS NULL THEN 1 ELSE 0 END) AS N_AUX
    FROM occ O WHERE O.FL_ABERTO = 1
    GROUP BY O.SITUACAO, O.PRAZO
    UNION ALL
    SELECT 'FUNIL', O.STATUS_ITEM, O.SITUACAO,
           COUNT(DISTINCT O.NUNOTA), COUNT(*), SUM(O.VLRTOT), 0
    FROM occ O WHERE O.FL_PERIODO = 1
    GROUP BY O.STATUS_ITEM, O.SITUACAO
    UNION ALL
    SELECT 'AGING', F.FAIXA, '-',
           COUNT(DISTINCT F.NUNOTA), COUNT(*), SUM(F.VLR_SALDO), 0
    FROM occ_fx F
    GROUP BY F.FAIXA
    UNION ALL
    SELECT 'PONTUALIDADE', P.CLASSE, '-',
           COUNT(DISTINCT P.NUNOTA), COUNT(*), SUM(P.VLRTOT), 0
    FROM occ_pont P
    GROUP BY P.CLASSE
    UNION ALL
    SELECT 'VINCULO', O.QUALIDADE_VINC, '-',
           COUNT(DISTINCT O.NUNOTA), COUNT(*), SUM(O.VLRTOT), 0
    FROM occ O WHERE O.FL_PERIODO = 1 AND O.QTDENT > 0
    GROUP BY O.QUALIDADE_VINC
    UNION ALL
    SELECT 'QUALIDADE', Q.CHAVE, '-',
           COUNT(DISTINCT Q.NUNOTA), COUNT(*), 0, 0
    FROM occ_q Q
    GROUP BY Q.CHAVE
)
SELECT B.BLOCO, B.CHAVE, B.CHAVE2, B.N_OCS, B.N_ITENS, ROUND(B.VLR, 2) AS VLR, B.N_AUX,
       TO_CHAR(JA.DT_BASE, 'YYYY-MM-DD') AS DT_BASE,
       JA.SNAPSHOT
FROM blocos B
CROSS JOIN jan JA
ORDER BY B.BLOCO, B.CHAVE, B.CHAVE2
