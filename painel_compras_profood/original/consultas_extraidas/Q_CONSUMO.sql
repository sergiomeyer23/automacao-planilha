             WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QTD_CONV > 0 THEN 1 / VO.QTD_CONV
        END AS FATOR
    FROM TGFCAB C
    JOIN (SELECT 99 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 100 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 1741 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 101 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 108 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 1742 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 1000 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1005 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1008 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1002 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1009 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1001 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1728 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1010 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1131 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1118 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1117 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1729 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1130 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1727 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1724 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1730 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1781 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1782 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1738 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1200 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL UNION ALL SELECT 1201 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL UNION ALL SELECT 1211 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL UNION ALL SELECT 1206 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL) TP ON TP.CODTIPOPER = C.CODTIPOPER AND TP.PAPEL = 'E