    JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    JOIN TGFPRO P ON P.CODPROD = I.CODPROD
    LEFT JOIN (
        SELECT CODPROD, CODVOL, MAX(DIVIDEMULTIPLICA) AS DM, MAX(QUANTIDADE) AS QTD_CONV,
               COUNT(DISTINCT DIVIDEMULTIPLICA || '|' || QUANTIDADE) AS N_REGRAS
        FROM TGFVOA WHERE NVL(ATIVO, 'S') = 'S' GROUP BY CODPROD, CODVOL
    ) VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
    WHERE I.PENDENTE = 'S'
      AND NVL(I.CANCELADO, 'N') <> 'S'
) X
WHERE X.QTD_ABERTA > 0
GROUP BY X.CODPROD, X.CODEMP) EM0
    CROSS JOIN prm PR
    WHERE (PR.CODEMP = 0 OR EM0.CODEMP = PR.CODEMP)
    GROUP BY EM0.CODPROD
),
ocx AS (
    SELECT OX.CODPROD, OX.NUNOTA, OX.SEQUENCIA, OX.CODEMP, OX.STATUS_OC, OX.QTD_PENDENTE,
           OX.VLR_UNIT, OX.DT_NEGOCIACAO
    FROM (SELECT
    Z.NUNOTA, Z.SEQUENCIA, Z.CODEMP, Z.CODPARC, Z.FORNECEDOR, Z.CODTIPOPER, Z.DESCRICAO_TOP,
    Z.CODPROD, Z.OS,
    Z.QTDNEG * NVL(Z.FATOR, 1)                                       AS QTD_NEGOCIADA,
    Z.QTDENTREGUE * NVL(Z.FATOR, 1)                                  AS QTD_ENTREGUE,
    CASE WHEN Z.ABERTA = 1 THEN (Z.QTDNEG - Z.QTDENTREGUE) * NVL(Z.FATOR, 1) ELSE 0 END AS QTD_PENDENTE,
    CASE WHEN Z.QTDNEG * NVL(Z.FATOR, 1) > 0 THEN Z.VLRTOT / (Z.QTDNEG * NVL(Z.FATOR, 1)) ELSE 0 END AS VLR_UNIT,
    Z.VLRTOT                                                         AS VLR_TOTAL,
    Z.DT_NEGOCIACAO,
    Z.DT_ENTREGA_PREVISTA,
    Z.PREVISAO_ORIGEM,
    NVL(Z.DT_LIBERACAO, CASE WHEN Z.STATUSNOTA = 'L' THEN Z.DT_NEGOCIACAO END) AS DT_APROVACAO,
    Z.DT_ENTREGA_REAL,
    CASE WHEN Z.CANCELADO = 'S'                              THEN 'CANCELADA'
