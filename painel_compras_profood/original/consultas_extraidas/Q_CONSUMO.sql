    FROM TGFCAB C
    JOIN (SELECT 99 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 100 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 1741 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 101 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 108 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 1742 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 1000 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1005 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1008 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1002 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1009 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1001 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1728 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1010 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1131 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1118 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1117 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1729 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1130 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1727 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1724 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1730 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1781 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1782 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1738 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1200 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL UNION ALL SELECT 1201 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL UNION ALL SELECT 1211 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL UNION ALL SELECT 1206 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL) TP ON TP.CODTIPOPER = C.CODTIPOPER AND TP.PAPEL IN ('CONSUMO', 'DEVOLUCAO', 'PERDA')
    JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    JOIN TGFPRO P ON P.CODPROD = I.CODPROD
    LEFT JOIN (
        SELECT CODPROD, CODVOL, MAX(DIVIDEMULTIPLICA) AS DM, MAX(QUANTIDADE) AS QTD_CONV,
               COUNT(DISTINCT DIVIDEMULTIPLICA || '|' || QUANTIDADE) AS N_REGRAS
        FROM TGFVOA WHERE NVL(ATIVO, 'S') = 'S' GROUP BY CODPROD, CODVOL
    ) VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
    WHERE C.DTNEG >= ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -36)
      AND C.STATUSNOTA = 'L'
) X
GROUP BY X.CODPROD, X.CODEMP, X.ANO_MES) CM
    CROSS JOIN prm PR
    CROSS JOIN jan2 J
    WHERE CM.ANO_MES >= TO_CHAR(J.INI, 'YYYY-MM')
      AND CM.ANO_MES <= TO_CHAR(J.FIM, 'YYYY-MM')
      AND (PR.CODEMP = 0 OR CM.CODEMP = PR.CODEMP)
    GROUP BY CM.CODPROD, CM.ANO_MES
),
