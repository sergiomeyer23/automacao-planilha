                    + 0.2 * NVL(CO.QTD_JANELA, 0) / DV.DIVISOR) AS MEDIA_PONDERADA,
        CASE UPPER(NVL(PD.CURVA_ABC, 'C')) WHEN 'A' THEN PR.COB_A WHEN 'B' THEN PR.COB_B ELSE PR.COB_C END AS COB_ALVO,
        PR.MEDIA_MODO, PR.DIAS_MES, PR.MARGEM, PR.COB_MAX, PR.SEG_FRAC
    FROM (SELECT
    P.CODPROD                                                AS CODPROD,
    P.DESCRPROD                                              AS DESCRPROD,
    P.REFERENCIA                                             AS REFERENCIA,
    P.CODVOL                                                 AS UNIDADE,
    P.MARCA                                                  AS MARCA,
    P.CODGRUPOPROD                                           AS GRUPO,
    G.DESCRGRUPOPROD                                         AS GRUPO_DESCR,
    CASE WHEN P.ATIVO = 'S' THEN 1 ELSE 0 END                AS FL_ATIVO,
    CASE WHEN P.LEADTIME > 0 THEN P.LEADTIME END             AS LEADTIME_PARAM_DIAS,
    CASE WHEN P.ESTMIN > 0 THEN P.ESTMIN END                 AS ESTOQUE_MIN_PARAM,
    CAST(NULL AS VARCHAR2(1))                                AS CURVA_ABC,
    CASE WHEN P.AGRUPMIN > 1 THEN P.AGRUPMIN END             AS MULTIPLO_COMPRA,
    CASE WHEN P.LOTECOMPMINIMO > 0 THEN P.LOTECOMPMINIMO END AS LOTE_MINIMO,
    0                                                        AS FL_SOB_ENCOMENDA,
    CASE WHEN NVL(P.CODPARCCONSIG, 0) > 0 THEN 1 ELSE 0 END  AS FL_CONSIGNADO
FROM TGFPRO P
LEFT JOIN TGFGRU G ON G.CODGRUPOPROD = P.CODGRUPOPROD) PD
    CROSS JOIN prm PR
    CROSS JOIN dvs DV
    LEFT JOIN est ES ON ES.CODPROD = PD.CODPROD
    LEFT JOIN emp EM ON EM.CODPROD = PD.CODPROD
    LEFT JOIN ocab OA ON OA.CODPROD = PD.CODPROD
    LEFT JOIN custo CU ON CU.CODPROD = PD.CODPROD
    LEFT JOIN cons CO ON CO.CODPROD = PD.CODPROD
    WHERE PD.FL_ATIVO = 1
),
med AS (
    SELECT BA.*,
           CASE WHEN BA.MEDIA_MODO = 1 THEN BA.MEDIA_PONDERADA ELSE BA.MEDIA_SIMPLES END AS MEDIA_USADA
    FROM base BA
),
dem AS (
    SELECT ME.*, ME.MEDIA_USADA / ME.DIAS_MES AS DEMANDA_DIARIA FROM med ME
),
cob AS (
    SELECT DE.*,
        CASE WHEN DE.DEMANDA_DIARIA > 0 THEN DE.QTD_DISPONIVEL / DE.DEMANDA_DIARIA ELSE 999 END AS DIAS_EST_ATUAL,
        CASE WHEN DE.DEMANDA_DIARIA > 0 THEN (DE.QTD_DISPONIVEL + DE.QTD_PENDENTE) / DE.DEMANDA_DIARIA ELSE 999 END AS DIAS_EST,
        DE.DEMANDA_DIARIA * DE.LEADTIME * (1 + DE.SEG_FRAC) AS EST_MIN_CALC,
        CASE WHEN DE.QTD_DISPONIVEL < 0 THEN -DE.QTD_DISPONIVEL * DE.VLR_UNIT ELSE 0 END AS RUPTURA_VALOR,
        CASE WHEN DE.FL_SOB_ENCOMENDA = 1 OR DE.FL_CONSIGNADO = 1 OR DE.QTD_JANELA <= 0 THEN 0
             ELSE GREATEST(0, DE.DEMANDA_DIARIA * (DE.LEADTIME + DE.COB_ALVO)
                              - (DE.QTD_DISPONIVEL + DE.QTD_PENDENTE)) END AS QTD_BRUTA
    FROM dem DE
),
mult AS (
    SELECT CB.*,
        CASE WHEN CB.QTD_BRUTA <= 0 THEN 0
             WHEN NVL(CB.MULTIPLO_COMPRA, 0) > 0 THEN CEIL(CB.QTD_BRUTA / CB.MULTIPLO_COMPRA) * CB.MULTIPLO_COMPRA
             ELSE CEIL(CB.QTD_BRUTA) END AS QTD_MULT
    FROM cob CB
),
sop AS (
    SELECT MU.*,
        CASE WHEN MU.QTD_MULT > 0 AND NVL(MU.LOTE_MINIMO, 0) > MU.QTD_MULT
             THEN CASE WHEN NVL(MU.MULTIPLO_COMPRA, 0) > 0
                       THEN CEIL(MU.LOTE_MINIMO / MU.MULTIPLO_COMPRA) * MU.MULTIPLO_COMPRA
                       ELSE MU.LOTE_MINIMO END
             ELSE MU.QTD_MULT END AS QTD_SUGERIDA,
        CASE WHEN MU.QTD_DISPONIVEL < 0 OR (MU.DEMANDA_DIARIA > 0 AND MU.DIAS_EST <= 0) THEN 'P1_CRITICO'
             WHEN MU.DEMANDA_DIARIA > 0 AND MU.DIAS_EST < MU.LEADTIME               THEN 'P2_RUPTURA_IMINENTE'
             WHEN MU.DEMANDA_DIARIA > 0 AND MU.DIAS_EST < MU.LEADTIME + MU.MARGEM   THEN 'P3_ATENCAO'
             WHEN MU.QTD_ESTOQUE > 0 AND MU.QTD_JANELA <= 0                         THEN 'P0_EXCESSO_SEM_GIRO'
             WHEN MU.DEMANDA_DIARIA > 0 AND MU.DIAS_EST > MU.COB_MAX                THEN 'P0_EXCESSO'
             ELSE 'OK' END AS PRIORIDADE,
        CASE WHEN MU.QTD_DISPONIVEL < 0                                             THEN 'RUPTURA'
             WHEN MU.DEMANDA_DIARIA > 0 AND MU.DIAS_EST < MU.LEADTIME               THEN 'PONTO_PEDIDO'
             WHEN MU.ESTOQUE_MIN_PARAM > 0 AND MU.QTD_DISPONIVEL < MU.ESTOQUE_MIN_PARAM THEN 'MINIMO_CURVA_A'
             ELSE 'SEM_DISPARO' END AS REGRA_DISPARO
    FROM mult MU
),
topn AS (
    SELECT S.CODPROD, S.DESCRPROD, S.UNIDADE, S.PRIORIDADE, S.MEDIA_USADA, S.MEDIA_SIMPLES,
           S.MEDIA_PONDERADA, S.QTD_JANELA, S.QTD_3M
    FROM sop S
    WHERE S.QTD_JANELA > 0
    ORDER BY S.QTD_JANELA DESC, S.CODPROD
    FETCH FIRST ? ROWS ONLY
)
SELECT T.CODPROD, T.DESCRPROD, T.UNIDADE, T.PRIORIDADE,
       ROUND(T.MEDIA_USADA, 2)      AS MEDIA_USADA,
       ROUND(T.MEDIA_SIMPLES, 2)    AS MEDIA_SIMPLES,
       ROUND(T.MEDIA_PONDERADA, 2)  AS MEDIA_PONDERADA,
       ROUND(T.QTD_3M / 3, 2)       AS MEDIA_3M,
       CASE WHEN T.MEDIA_USADA > 0 THEN ROUND((T.QTD_3M / 3) / T.MEDIA_USADA - 1, 4) END AS DESVIO,
       ROUND(T.QTD_JANELA, 2)       AS QTD_JANELA,
       CM.ANO_MES,
       ROUND(CM.QTD, 2)             AS QTD,
       TO_CHAR(J.INI, 'YYYY-MM')    AS JANELA_INI_AM,
       TO_CHAR(J.FIM, 'YYYY-MM')    AS JANELA_FIM_AM,
       DV.DIVISOR, DV.ORIGEM_DIVISOR
FROM topn T
CROSS JOIN jan2 J
CROSS JOIN dvs DV
LEFT JOIN cons_mes CM ON CM.CODPROD = T.CODPROD
ORDER BY T.QTD_JANELA DESC, T.CODPROD, CM.ANO_MES
