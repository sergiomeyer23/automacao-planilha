         WHEN Z.PENDENTE = 'N' AND Z.QTDENTREGUE > 0         THEN 'ENCERRADA_PARCIAL'
         WHEN Z.PENDENTE = 'N'                               THEN 'ENCERRADA_SEM_RECEBER'
         WHEN Z.QTDENTREGUE > 0                              THEN 'ENTREGA_PARCIAL'
         WHEN Z.STATUSNOTA = 'L'                             THEN 'APROVADA_NAO_ENTREGUE'
         ELSE 'ABERTA_NAO_APROVADA'
    END                                                              AS STATUS_OC,
    CASE WHEN Z.ABERTA = 1 AND Z.DT_ENTREGA_PREVISTA < TRUNC(SYSDATE)
              THEN TRUNC(SYSDATE) - Z.DT_ENTREGA_PREVISTA
         WHEN Z.QTDNEG > 0 AND Z.QTDENTREGUE >= Z.QTDNEG
              AND Z.DT_ENTREGA_REAL IS NOT NULL AND Z.DT_ENTREGA_PREVISTA IS NOT NULL
              THEN Z.DT_ENTREGA_REAL - Z.DT_ENTREGA_PREVISTA
