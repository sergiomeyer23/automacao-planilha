WITH prm AS (
    SELECT
        TO_NUMBER(?)          AS CODEMP,
        TO_NUMBER(?) / 10000  AS DIAS_MES,
        TO_NUMBER(?)          AS MARGEM,
        TO_NUMBER(?)          AS COB_MAX,
        TO_NUMBER(?) / 10000  AS SEG_FRAC,
        TO_NUMBER(?)          AS COB_A,
        TO_NUMBER(?)          AS COB_B,
        TO_NUMBER(?)          AS COB_C,
        TO_NUMBER(?)          AS LT_PADRAO,
        TO_NUMBER(?)          AS MEDIA_MODO,
        TO_NUMBER(?)          AS MESES_MEDIA,
        TO_NUMBER(?)          AS DIVISOR_MEDIA,
        TO_NUMBER(?)          AS INCLUI_MES_ATUAL
    FROM DUAL
), jan AS (
    SELECT
        CASE WHEN PR.INCLUI_MES_ATUAL = 1 THEN TRUNC(SYSDATE, 'MM')
             ELSE ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -1) END AS FIM,
        GREATEST(1, PR.MESES_MEDIA) AS NMESES
    FROM prm PR
),
jan2 AS (
    SELECT JA.FIM, JA.NMESES, ADD_MONTHS(JA.FIM, 1 - JA.NMESES) AS INI FROM jan JA
),
cons_mes AS (
    SELECT CM.CODPROD, CM.ANO_MES,
           SUM(NVL(CM.QTD_VENDA, 0) + NVL(CM.QTD_PERDA, 0) - NVL(CM.QTD_DEVOLUCAO, 0)) AS QTD
    FROM (SELECT
    X.CODPROD                                                     AS CODPROD,
    X.CODEMP                                                      AS CODEMP,
    X.ANO_MES                                                     AS ANO_MES,
    SUM(CASE WHEN X.PAPEL = 'CONSUMO'   THEN X.QTD_BASE ELSE 0 END) AS QTD_VENDA,
    SUM(CASE WHEN X.PAPEL = 'DEVOLUCAO' THEN X.QTD_BASE ELSE 0 END) AS QTD_DEVOLUCAO,
    SUM(CASE WHEN X.PAPEL = 'PERDA'     THEN X.QTD_BASE ELSE 0 END) AS QTD_PERDA,
    SUM(CASE WHEN X.PAPEL = 'DEVOLUCAO' THEN -X.QTD_BASE ELSE X.QTD_BASE END) AS QTD_CONSUMO,
    SUM(CASE WHEN X.PAPEL = 'DEVOLUCAO' THEN -X.VLR ELSE X.VLR END)           AS VLR_CONSUMO,
    SUM(CASE WHEN X.FATOR IS NULL THEN 1 ELSE 0 END)              AS ITENS_SEM_CONVERSAO
FROM (
    SELECT
        I.CODPROD, C.CODEMP, TP.PAPEL,
        TO_CHAR(C.DTNEG, 'YYYY-MM')                 AS ANO_MES,
        NVL(I.QTDNEG, 0) * NVL(
            CASE WHEN I.CODVOL = P.CODVOL THEN 1
                 WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QTD_CONV > 0 THEN VO.QTD_CONV
                 WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QTD_CONV > 0 THEN 1 / VO.QTD_CONV
            END, 1)                                  AS QTD_BASE,
        NVL(I.VLRTOT, 0)                             AS VLR,
        CASE WHEN I.CODVOL = P.CODVOL THEN 1
             WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QTD_CONV > 0 THEN VO.QTD_CONV
             WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QTD_CONV > 0 THEN 1 / VO.QTD_CONV
