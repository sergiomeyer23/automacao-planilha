-- Parâmetros (ordem dos ?): CODEMP
-- Tipos: I

WITH prm AS (
    SELECT TO_NUMBER(?) AS CODEMP FROM DUAL
),
ab AS (
    SELECT O.NUNOTA, O.QTD_PENDENTE * O.VLR_UNIT AS VLR, TRUNC(SYSDATE) - O.DT_NEGOCIACAO AS IDADE
    FROM (SELECT
    Z.NUNOTA, Z.SEQUENCIA, Z.CODEMP, Z.CODPARC, Z.FORNECEDOR, Z.CODTIPOPER, Z.DESCRICAO_TOP,
    Z.CODPROD, Z.OS,
    Z.QTDNEG * NVL(Z.FATOR, 1)                                       AS QTD_NEGOCIADA,
    Z.QTDENTREGUE * NVL(Z.FATOR, 1)                                  AS QTD_ENTREGUE,
    CASE WHEN Z.ABERTA = 1 THEN (Z.QTDNEG - Z.QTDENTREGUE) * NVL(Z.FATOR, 1) ELSE 0 END AS QTD_PENDENTE,
    CASE WHEN Z.QTDNEG * NVL(Z.FATOR, 1) > 0 THEN Z.VLRTOT / (Z.QTDNEG * NVL(Z.FATOR, 1)) ELSE 0 END AS VLR_UNIT,
    Z.VLRTOT                                                         AS VLR_TOTAL,
    Z.DT_NEGOCIACAO,
    Z.DT_ENTREGA_PREVISTA,
    Z.PREVISAO_ORIGEM,
    NVL(Z.DT_LIBERACAO, CASE WHEN Z.STATUSNOTA = 'L' THEN Z.DT_NEGOCIACAO END) AS DT_APROVACAO,
    Z.DT_ENTREGA_REAL,
    CASE WHEN Z.CANCELADO = 'S'                              THEN 'CANCELADA'
         WHEN Z.QTDNEG > 0 AND Z.QTDENTREGUE >= Z.QTDNEG     THEN 'ENTREGUE'
         WHEN Z.PENDENTE = 'N' AND Z.QTDENTREGUE > 0         THEN 'ENCERRADA_PARCIAL'
         WHEN Z.PENDENTE = 'N'                               THEN 'ENCERRADA_SEM_RECEBER'
         WHEN Z.QTDENTREGUE > 0                              THEN 'ENTREGA_PARCIAL'
         WHEN Z.STATUSNOTA = 'L'                             THEN 'APROVADA_NAO_ENTREGUE'
         ELSE 'ABERTA_NAO_APROVADA'
    END                                                              AS STATUS_OC,
    CASE WHEN Z.ABERTA = 1 AND Z.DT_ENTREGA_PREVISTA < TRUNC(SYSDATE)
              THEN TRUNC(SYSDATE) - Z.DT_ENTREGA_PREVISTA
         WHEN Z.QTDNEG > 0 AND Z.QTDENTREGUE >= Z.QTDNEG
              AND Z.DT_ENTREGA_REAL IS NOT NULL AND Z.DT_ENTREGA_PREVISTA IS NOT NULL
              THEN Z.DT_ENTREGA_REAL - Z.DT_ENTREGA_PREVISTA
         ELSE 0
    END                                                              AS DIAS_ATRASO,
    CASE WHEN Z.FATOR IS NULL THEN 1 ELSE 0 END                      AS FL_SEM_CONVERSAO
FROM (
    SELECT Y.*,
        CASE WHEN Y.CANCELADO <> 'S' AND Y.PENDENTE = 'S' AND Y.QTDENTREGUE < Y.QTDNEG THEN 1 ELSE 0 END AS ABERTA,
        CASE WHEN Y.QTDENTREGUE > 0 THEN COALESCE(
            (SELECT TRUNC(MAX(N.DTNEG)) FROM TGFVAR V JOIN TGFCAB N ON N.NUNOTA = V.NUNOTA
              WHERE V.NUNOTAORIG = Y.NUNOTA AND V.SEQUENCIAORIG = Y.SEQUENCIA AND V.NUNOTA <> Y.NUNOTA),
            CASE WHEN Y.OS IS NOT NULL THEN
                (SELECT TRUNC(MAX(N.DTNEG)) FROM TGFITE E JOIN TGFCAB N ON N.NUNOTA = E.NUNOTA
                  WHERE N.CODTIPOPER IN (259, 200) AND N.STATUSNOTA = 'L'
                    AND TRIM(E.AD_OS) = Y.OS AND E.CODPROD = Y.CODPROD
                    AND N.DTNEG >= Y.DT_NEGOCIACAO - 365)
            END)
        END AS DT_ENTREGA_REAL
    FROM (
        SELECT
            C.NUNOTA, I.SEQUENCIA, C.CODEMP, C.CODPARC, PA.NOMEPARC AS FORNECEDOR,
            C.CODTIPOPER, T.DESCROPER AS DESCRICAO_TOP, I.CODPROD,
            TRIM(C.AD_OSTUICIAL)                     AS OS,
            C.STATUSNOTA, NVL(I.PENDENTE, 'S')       AS PENDENTE, NVL(I.CANCELADO, 'N') AS CANCELADO,
            NVL(I.QTDNEG, 0)                         AS QTDNEG,
            NVL(I.QTDENTREGUE, 0)                    AS QTDENTREGUE,
            NVL(I.VLRTOT, 0)                         AS VLRTOT,
            TRUNC(C.DTNEG)                           AS DT_NEGOCIACAO,
            COALESCE(TRUNC(C.DTPREVENT), TRUNC(C.DTNEG) + CASE WHEN P.LEADTIME > 0 THEN P.LEADTIME END) AS DT_ENTREGA_PREVISTA,
            CASE WHEN C.DTPREVENT IS NOT NULL THEN 'DTPREVENT'
                 WHEN P.LEADTIME > 0 THEN 'OC+LEADTIME' END AS PREVISAO_ORIGEM,
            (SELECT TRUNC(MAX(L.DHLIB)) FROM TSILIB L
              WHERE L.TABELA = 'TGFCAB' AND L.NUCHAVE = C.NUNOTA
                AND L.DHLIB IS NOT NULL AND NVL(L.REPROVADO, 'N') <> 'S') AS DT_LIBERACAO,
            CASE WHEN I.CODVOL = P.CODVOL THEN 1
                 WHEN VO.N_REGRAS = 1 AND VO.DM = 'M' AND VO.QTD_CONV > 0 THEN VO.QTD_CONV
                 WHEN VO.N_REGRAS = 1 AND VO.DM = 'D' AND VO.QTD_CONV > 0 THEN 1 / VO.QTD_CONV
            END                                      AS FATOR
        FROM TGFCAB C
        JOIN (SELECT 99 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 100 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 1741 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 101 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 108 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 1742 AS CODTIPOPER, 'ORDEM_COMPRA' AS PAPEL FROM DUAL UNION ALL SELECT 1000 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1005 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1008 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1002 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1009 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1001 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1728 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1010 AS CODTIPOPER, 'EMPENHO' AS PAPEL FROM DUAL UNION ALL SELECT 1131 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1118 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1117 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1729 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1130 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1727 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1724 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1730 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1781 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1782 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1738 AS CODTIPOPER, 'CONSUMO' AS PAPEL FROM DUAL UNION ALL SELECT 1200 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL UNION ALL SELECT 1201 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL UNION ALL SELECT 1211 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL UNION ALL SELECT 1206 AS CODTIPOPER, 'DEVOLUCAO' AS PAPEL FROM DUAL) TP ON TP.CODTIPOPER = C.CODTIPOPER AND TP.PAPEL = 'ORDEM_COMPRA'
        JOIN TGFTOP T ON T.CODTIPOPER = C.CODTIPOPER AND T.DHALTER = C.DHTIPOPER
        JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
        JOIN TGFPRO P ON P.CODPROD = I.CODPROD
        LEFT JOIN TGFPAR PA ON PA.CODPARC = C.CODPARC
        LEFT JOIN (
            SELECT CODPROD, CODVOL, MAX(DIVIDEMULTIPLICA) AS DM, MAX(QUANTIDADE) AS QTD_CONV,
                   COUNT(DISTINCT DIVIDEMULTIPLICA || '|' || QUANTIDADE) AS N_REGRAS
            FROM TGFVOA WHERE NVL(ATIVO, 'S') = 'S' GROUP BY CODPROD, CODVOL
        ) VO ON VO.CODPROD = I.CODPROD AND VO.CODVOL = I.CODVOL
        WHERE C.DTNEG >= ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -24)
    ) Y
) Z) O
    CROSS JOIN prm PR
    WHERE O.STATUS_OC IN ('ABERTA_NAO_APROVADA', 'APROVADA_NAO_ENTREGUE', 'ENTREGA_PARCIAL')
      AND O.QTD_PENDENTE > 0
      AND (PR.CODEMP = 0 OR O.CODEMP = PR.CODEMP)
),
fx AS (
    SELECT AB0.NUNOTA, AB0.VLR,
           CASE WHEN AB0.IDADE <= 15 THEN 1 WHEN AB0.IDADE <= 30 THEN 2 WHEN AB0.IDADE <= 60 THEN 3 ELSE 4 END AS ORDEM
    FROM ab AB0
)
SELECT FX0.ORDEM,
       CASE FX0.ORDEM WHEN 1 THEN '0-15' WHEN 2 THEN '16-30' WHEN 3 THEN '31-60' ELSE '60+' END AS FAIXA,
       COUNT(DISTINCT FX0.NUNOTA) AS N_OCS,
       COUNT(*)                   AS N_ITENS,
       ROUND(SUM(FX0.VLR), 2)     AS VLR_PENDENTE
FROM fx FX0
GROUP BY FX0.ORDEM
ORDER BY FX0.ORDEM
